//! Tests for line accounting and the two content sniffs.

use super::*;

/// A line holding both code and a trailing comment is **code**: the question is how much
/// the model wrote, and a line that does something is a line that does something.
#[test]
fn a_line_with_code_and_a_trailing_comment_is_code() {
    let counts = count_lines("let a = 1; // set it\n", CommentStyle::CFamily);
    assert_eq!(
        counts,
        LineCounts {
            code: 1,
            comment: 0,
            blank: 0
        }
    );
}

/// A blank line inside a block comment is part of the prose, not whitespace — otherwise a
/// long doc comment reads as an empty file.
#[test]
fn a_block_comment_holds_its_blank_lines() {
    let source = "/*\n * one\n\n * two\n */\nlet a = 1;\n";
    let counts = count_lines(source, CommentStyle::CFamily);
    assert_eq!(counts.code, 1);
    assert_eq!(counts.comment, 5);
    assert_eq!(counts.blank, 0);
    assert_eq!(counts.total(), 6);
}

/// Code after a block comment closes on the same line still counts.
#[test]
fn code_after_a_closing_block_comment_counts() {
    let counts = count_lines("/* note */ let a = 1;\n", CommentStyle::CFamily);
    assert_eq!(counts.code, 1);
    assert_eq!(counts.comment, 0);
}

/// A file with no recognised comment syntax counts every non-blank line as code, which is
/// what "counted for size only" means for JSON, Markdown and data.
#[test]
fn a_file_with_no_comment_style_is_all_code_and_blanks() {
    let counts = count_lines("{\n  \"a\": 1\n\n}\n", CommentStyle::None);
    assert_eq!(counts.code, 3);
    assert_eq!(counts.comment, 0);
    assert_eq!(counts.blank, 1);
}

#[test]
fn a_nul_byte_marks_a_file_binary() {
    assert!(looks_binary(&[0x89, b'P', b'N', b'G', 0x00, 0x01]));
    assert!(!looks_binary(b"export const a = 1;\n"));
}

#[test]
fn a_generator_banner_is_recognised_only_at_the_top() {
    assert!(looks_generated(
        "// @generated by tcab\nexport const a = 1;\n"
    ));
    assert!(looks_generated(
        "/* Code generated by protoc. DO NOT EDIT. */\n"
    ));
    // Six lines down is prose about generation, not a banner.
    let discussion = "a\nb\nc\nd\ne\n// this file is @generated somewhere else\n";
    assert!(!looks_generated(discussion));
}

/// Two files' counts fold independently.
#[test]
fn counts_accumulate() {
    let mut total = LineCounts::default();
    total.add(count_lines("let a = 1;\n", CommentStyle::CFamily));
    total.add(count_lines("// note\n\n", CommentStyle::CFamily));
    assert_eq!(
        total,
        LineCounts {
            code: 1,
            comment: 1,
            blank: 1
        }
    );
}

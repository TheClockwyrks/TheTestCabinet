/// The header stamped on every generated module of the backend API package.
const API_TS_HEADER: &str = "\
// @generated by `api-codegen`. DO NOT EDIT BY HAND.
//
// Regenerate with `npm run gen:contract` (which runs `cargo run -p api-codegen`
// and formats the output). The source of truth is the Rust API types in
// `crates/backend` and `crates/core`, which derive `ts_rs::TS` +
// `schemars::JsonSchema` behind their `contract` feature. The JSON Schemas under
// `apps/docs/public/schema/` are generated from the same types in the same pass.\n\n";

/// The directory, relative to this workspace's root, that the backend's JSON Schema
/// documents are written under: where the documentation site publishes them from.
/// Every document here lives in a directory of its own (`backend-api/`, `coverage/`,
/// `jobs-api/`, `snapshot/`), never in one of the data contract's (`core/`, `gg/`),
/// which `contract-codegen` owns.
const SCHEMA_DIR: &str = "apps/docs/public/schema";

/// The package holding the backend's API: what the console and the gallery read
/// from the backend and its published snapshot, beside the data contract it carries
/// (`@clockwyrks/run-record`). Like the run-record package it is never vendored into
/// a run.
const BACKEND_API_PKG: &str = "@clockwyrks/backend-api";

/// The tournament schema's `$defs`. `AdversarialOutcome` is *not* listed: it is
/// owned by the run-record schema, so a reference to it is rewritten to a
/// cross-document `$ref` at that schema's URL.
const TOURNAMENT_DEFS: &[&str] = &[
    "MatchSummary",
    "Standing",
    "ControllerRef",
    "ControllerKind",
];

/// The review schema's `$defs`: the canonical home of the review value types, so
/// the backend and snapshot documents (and the console that submits reviews) all
/// reference them here rather than each carrying a copy.
const REVIEW_DEFS: &[&str] = &[
    "Rating",
    "AestheticRating",
    "FailureCap",
    "VerdictStatus",
    "ReviewVerdict",
    "DomainRating",
    "DomainAesthetic",
    "RatingChange",
    "AestheticChange",
    "VerdictChange",
    "WriteupChange",
    "ReviewDiff",
    "ReviewRevision",
];

/// This workspace's root, resolved from this crate's own compile-time manifest dir
/// (`crates/api-codegen` → two levels up). Not `contract_codegen::workspace_root`:
/// that one is evaluated in the contract generator's crate, so it names the
/// workspace that crate sits in, which need not be this one.
fn workspace_root() -> Result<PathBuf> {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .ancestors()
        .nth(2)
        .map(Path::to_path_buf)
        .context("resolving the workspace root from CARGO_MANIFEST_DIR")
}


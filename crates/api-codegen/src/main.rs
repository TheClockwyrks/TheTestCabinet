//! `api-codegen` — the generator for the backend's API package.
//!
//! It emits the TypeScript bindings of `@clockwyrks/backend-api`
//! (`packages/backend-api/src/*.ts`, via `ts_rs`) and the JSON Schemas of the
//! backend's documents (under `apps/docs/public/schema/`, via `schemars`) from the
//! types in `crates/backend` and `crates/core` that derive `TS` + `JsonSchema` behind
//! their `contract` feature: the HTTP API's request and response shapes, the run
//! queue, coverage plans and ladders, the published snapshot documents, accounts,
//! comparisons and the persisted tournament.
//!
//! Those types refer to the data contract (a snapshot carries a run record, a ladder
//! gates on a review rating), which `contract-codegen` writes. So this generator
//! takes that generator's modules and documents as *external* homes
//! ([`contract_codegen::contract_modules`], [`contract_codegen::contract_schema_docs`]):
//! they are not written here, but an import of a contract type resolves to
//! `@clockwyrks/run-record` and a `$ref` to one resolves to the contract document's
//! URL. Nothing in the data contract refers back to a type here.
//!
//! Run it with `cargo run -p api-codegen`, or `npm run gen:contract`, which runs both
//! generators and normalizes the output with Prettier.


/// `csv-tools` → `csv_tools`, `my_helpers.v2` → `my_helpers_v2`, `9lives` → `_9lives`.
///
/// snake_case because that is what Rust spells a name in and what this SDK spells every bound
/// function in, so a program reaching `csv_tools::parse(…)` reads like the rest of its own scope.
/// Any separator — `-`, `.`, or anything a name should not have had — becomes `_`, a run of them
/// becomes one, an upper-case letter is lowered, a name that is nothing but separators becomes
/// `module`, and a leading digit is prefixed.
///
/// It has to be a valid Rust **identifier** for a stronger reason than any other arm's does: on this
/// arm the key is a **crate name** the compiler resolves a path from, not a string looked up at run
/// time, so a key Rust could not parse would be a program that does not compile rather than a call
/// that fails.
///
/// A key that would name a crate the compile already has takes the same leading underscore a keyword
/// does — the SDK, every crate in the shipped [library set](compile::library_crate_names), the
/// program's own crate name and the [sysroot crates](SYSROOT) a program reaches without asking.
/// Handing `std` or `gg` to `--extern` would either shadow a crate a model was told it may write or
/// leave `rustc` choosing between two candidates for one name, and both fail a program that is
/// correct.
///
/// Deliberately ASCII-only, though Rust identifiers may be Unicode, for the reason every other arm
/// gives: a name a model has to reproduce exactly is one that should have no characters it could get
/// wrong.
pub(super) fn binding_name(name: &str) -> String {
    let mut out = String::new();
    let mut separated = false;
    for ch in name.chars() {
        if ch.is_ascii_alphanumeric() {
            if separated && !out.is_empty() {
                out.push('_');
            }
            separated = false;
            out.extend(ch.to_lowercase());
        } else {
            separated = true;
        }
    }
    if out.is_empty() {
        return "module".to_string();
    }
    if out.starts_with(|ch: char| ch.is_ascii_digit()) || is_taken(&out) {
        out.insert(0, '_');
    }
    out
}

/// Whether `key` is a word this arm cannot bind a module under.
fn is_taken(key: &str) -> bool {
    RESERVED.contains(&key)
        || SYSROOT.contains(&key)
        || key == source::CRATE_NAME
        || compile::library_crate_names().any(|library| library == key)
}

/// The crates the sysroot puts in front of every program: a module bound under one of these names
/// would take the standard library's place in the extern prelude.
const SYSROOT: [&str; 5] = ["std", "core", "alloc", "proc_macro", "test"];

/// Every word `rustc` refuses as a path segment: the 2021 edition's strict keywords and the ones it
/// reserves for later.
///
/// `crate`, `self`, `super` and `Self` are among them and are the sharpest of the set — each parses
/// and means something else entirely, so a module bound at one would resolve to somewhere other than
/// the module. The weak keywords (`macro_rules`, `union`, `raw`) are absent: each is a legal
/// identifier.
const RESERVED: [&str; 51] = [
    "abstract", "as", "async", "await", "become", "box", "break", "const", "continue", "crate",
    "do", "dyn", "else", "enum", "extern", "false", "final", "fn", "for", "if", "impl", "in",
    "let", "loop", "macro", "match", "mod", "move", "mut", "override", "priv", "pub", "ref",
    "return", "self", "static", "struct", "super", "trait", "true", "try", "type", "typeof",
    "unsafe", "unsized", "use", "virtual", "where", "while", "yield", "gen",
];

/// `gg::views::open_file("src/main.rs", gg::views::ViewOptions::default())?;`, or the same call with
/// a `gg::views::ViewOptions { offset: Some(400), limit: Some(200), ..Default::default() }` for a
/// window — with the call itself already spelled by the language that asked.
///
/// Deliberately the plainest statement that does the job: no binding, no printing. It is synthesized
/// into the agent's own transcript and read by the model as an example of its own output, so
/// anything clever in it is a style the run did not intend to teach. The one thing it *does* teach is
/// the `?`, which is not decoration — the `fn main` it lives in returns `Result<(), gg::Failure>`,
/// and a call whose `Result` went unused would be the model's first example of ignoring a failure.
///
/// The window is two of the three fields of this arm's options struct, and the third — the cut a
/// view's long lines get — is left to a `..Default::default()` tail: `gg::views::ViewOptions` has a
/// field this statement does not set, and writing `max_line_chars: None` out beside two `Some`s is
/// a construction a Rust author would not write where the language's own idiom for "the rest as
/// default" exists.
///
/// The struct is written **in full**, `gg::` and all, for the reason every synthesized call is: gg
/// writes no `use` line into a program and there is none above this statement, so a bare
/// `ViewOptions` — or a module-qualified `views::ViewOptions` — would be a text gg put in the
/// model's own transcript that does not compile.
///
/// The path is rendered through [`serde_json`] so a quote or a backslash in one cannot produce a
/// statement that would not parse: Rust's string literals accept exactly the escapes JSON's do.
pub(super) fn open_file_statement(
    open_file: &str,
    path: &str,
    window: Option<FileWindow>,
) -> String {
    let path = serde_json::Value::String(path.to_string());
    let options = format!("{SDK_CRATE}::views::ViewOptions");
    match window {
        Some(window) => format!(
            "{open_file}({path}, {options} {{ offset: Some({}), limit: Some({}), \
             ..Default::default() }})?;",
            window.offset, window.limit
        ),
        None => format!("{open_file}({path}, {options}::default())?;"),
    }
}

/// A whole program: an array of names and a `for` over it, each iteration opening one documentation
/// view.
///
/// A **whole program** rather than a statement list, because Rust has nowhere for a statement to
/// live outside a function body — and because that is what the seam asks for anyway: the on-use
/// script of every [built-in family skill](crate::skills) is a program that is prepared and run.
///
/// An array and a loop rather than one statement per name because the list is as long as the family
/// — eleven calls written out would be a program a model reads as a style to copy — and an **array**
/// rather than a `Vec` because it is a fixed list of `&'static str` and `vec![]` would allocate for
/// nothing. `for name in functions` iterates it by value, which is what a Rust author writes for an
/// array of `Copy` elements.
///
/// The empty case carries a type annotation, because an empty array literal has no element type to
/// infer and `[]` alone is `E0282`.
pub(super) fn open_docs_views_statement(open_docs_view: &str, names: &[&str]) -> String {
    main_program(&open_docs_views_body(open_docs_view, names))
}

/// The array and the `for` that [`open_docs_views_statement`] wraps a `fn main` around, as a body a
/// statement can be written above — which is what the [opening turn](bootstrap_program) does with
/// it, so the loop a model reads there is character for character the one every other program gg
/// writes on this arm shows it.
fn open_docs_views_body(open_docs_view: &str, names: &[&str]) -> String {
    let entries: Vec<String> = names
        .iter()
        .map(|name| format!("        {}", serde_json::Value::String((*name).to_string())))
        .collect();
    let listed = match entries.is_empty() {
        true => "    let functions: [&str; 0] = [];\n".to_string(),
        false => format!("    let functions = [\n{},\n    ];\n", entries.join(",\n")),
    };
    format!(
        "{listed}\
         \x20   for name in functions {{\n\
         \x20       {open_docs_view}(name)?;\n\
         \x20   }}\n"
    )
}

/// A whole program that opens one file view per entry of `views`: a `fn main` and one call in the
/// order given.
///
/// The seam's default is the statement list, and this arm cannot take it: a Rust file has nowhere
/// for a statement to live outside a function body, so what gg pushes into the transcript has to be
/// a program the model really could have sent. Each call is written by [`open_file_statement`], so
/// the one place a file-view call is spelled stays one place.
pub(super) fn open_file_program(open_file: &str, views: &[(&str, Option<FileWindow>)]) -> String {
    let calls: String = views
        .iter()
        .map(|(path, window)| format!("    {}\n", open_file_statement(open_file, path, *window)))
        .collect();
    main_program(&calls)
}

/// The `fn main` every program gg synthesizes for this arm is written as, around `body`.
///
/// `Result<(), gg::Failure>` rather than `()`, because every call in every body gg writes is
/// composed with `?` — and because it is the shape this arm's prompt tells a model to write, so a
/// program in the model's own transcript that used a different one would be teaching against it.
///
/// It writes **no `use` line**, and that is not an omission: every call gg synthesizes is spelled in
/// full out of the catalogue (`gg::views::open_file`), which `--extern gg=…` makes reachable with no
/// line at all. A `use` gg wrote here would be gg teaching an import the program does not need.
fn main_program(body: &str) -> String {
    format!("fn main() -> Result<(), {SDK_CRATE}::Failure> {{\n{body}    Ok(())\n}}\n")
}

/// The opening turn: **one** search listing every module the agent holds, then the array of
/// documentation keys and a `for` over it, each call composed with `?`.
///
/// One call rather than one per module, because a `modules` filter is a **union**: the modules a
/// run granted come back as a single directory, so the shape a model reads first — and the shape it
/// will copy — is one call carrying a list rather than a loop asking the same question a module at
/// a time. It carries no query at all, because a module filter alone *is* the directory and a word
/// beside it would narrow the very listing this is here to open, and it asks for
/// [`MAX_SEARCH_LIMIT`], because the whole of a module is the point rather than its first page.
///
/// The list is written **inline in the call**, unlike the keys below it: it is the agent's `files`
/// and `shell` and nothing else, so a binding above the call would name two strings once each. The
/// keys keep their array and their `for` — and their type annotation when they are none — for the
/// reasons [`open_docs_views_statement`] gives.
///
/// An agent that holds neither module gets the search **left out entirely** rather than written
/// with an empty list: nothing to look for and nothing to look in is `invalid-argument`, so that
/// call would open the session with a failure and with a worked example of the shape that failed.
///
/// A call with two or more optional arguments takes an **options struct with a `Default`, filled in
/// with functional-update syntax**, which is this language's idiom and the one its SDK declares.
///
/// Every call returns a `Result` and every one is propagated with `?`, which is this arm's failure
/// model: a bootstrap that unwrapped, or ignored, what a call handed back would be a worked example
/// of the two things this language's programs are written not to do.
pub(super) fn bootstrap_program(
    search: &str,
    open_docs_view: &str,
    modules: &[&str],
    docs: &[&str],
) -> String {
    let views = open_docs_views_body(open_docs_view, docs);
    if modules.is_empty() {
        return main_program(&views);
    }
    let listed: Vec<String> = modules
        .iter()
        .map(|path| serde_json::Value::String((*path).to_string()).to_string())
        .collect();
    let options = format!("{}::SearchOptions", module_of(search));
    let listing = format!(
        "    {search}({options} {{\n\
         \x20       modules: &[{}],\n\
         \x20       limit: Some({MAX_SEARCH_LIMIT}),\n\
         \x20       ..Default::default()\n\
         \x20   }})?;\n",
        listed.join(", ")
    );
    main_program(&format!("{listing}\n{views}"))
}

/// The module a fully-qualified call is filed under, taken off the front of the call itself.
///
/// The one thing gg has to write here that is a **type** rather than a call, and it is derived from
/// the call rather than written down beside it so the two cannot disagree: this SDK declares a
/// call's options struct in the module the call itself lives in. Every catalogued name is
/// module-qualified — the name rule (`signatures.fqn.rs`) is what makes that true on every arm — so
/// a call that somehow carried no qualifier is used as its own module rather than crashing a turn.
fn module_of(call: &str) -> &str {
    call.rsplit_once("::").map_or(call, |(module, _)| module)
}


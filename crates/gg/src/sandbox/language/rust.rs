//! **Rust** — the first arm whose component is compiled **per turn**, because the program and the
//! artifact are the same object.
//!
//! Everything this arm owns lives here or in one of this module's siblings:
//!
//! * [`compile`] — the host-side `rustc` and the in-process component encode, what they cost, what
//!   they share, and the two failures they tell apart;
//! * [`source`] — what gg writes around a model's Rust (nothing), the names a compile is written
//!   under, and the reading of a code module's exports;
//! * `packages/gg-sandbox-rust/` — the crate a program is compiled against: the SDK, the shell, the
//!   curated library set, and the build that cuts them;
//! * `rust.libraries.tar.gz`, `rust.adapter.wasm` and `rust.toolchain.json` — the compiled library
//!   set, the pinned preview1 reactor adapter the encode needs, and what built them, generated by
//!   `crates/gg-sandbox-artifacts/rust` into this build's own `OUT_DIR` rather than committed
//!   anywhere, and reached through `GG_ARTIFACTS_RUST`;
//! * the **signature catalogue**, which is the whole of what a model is told about this surface —
//!   reflected out of the SDK's own rustdoc and generated into this build's `OUT_DIR` rather than
//!   committed anywhere (see `crates/gg/build.rs`).
//!
//! # Why this arm has no guest component at all
//!
//! Every arm before it evaluates a **string**. Python's baked component holds a whole CPython,
//! Ruby's holds Opal, the ECMAScript one holds a JavaScript engine, and a program crosses the
//! membrane as source those runtimes read. Rust has no runtime of that kind: `rustc` does not
//! produce a Rust interpreter that later runs a program, it produces the program. There is no
//! artifact of this language that is not one particular program, so there is nothing to bake and
//! nothing a per-process cache could hold.
//!
//! That is the shape the seam grew for. [`PreparedProgram::component`](super::PreparedProgram)
//! carries the bytes a preparation compiled, [`guest_component`](super::ProgramLanguage) answers
//! `None`, and [`program_component`](super::super::engine) is where the two shapes of arm meet. The
//! C++ and Swift arms are the same shape and inherit it.
//!
//! # What a Rust program is, here
//!
//! A **whole Rust program**: the `use` lines the model wrote and the `fn main` it declared, compiled
//! as a binary crate under the name `program`. gg writes no prologue, no epilogue, no entry point
//! and no import — the file `rustc` reads is the file the model sent, so every diagnostic and every
//! panic is already in the model's own coordinates and there is nothing to correct.
//!
//! `fn main() -> Result<(), gg::Failure>` is the shape to write against a `Result`-returning SDK,
//! because it is what makes `?` compose; a plain `fn main()` is a Rust program too, and there `?` is
//! Rust's own `E0277` rather than anything gg decided. What calls that `main` is
//! `packages/gg-sandbox-rust/src/program.rs`, through the unmangled C entry symbol `rustc` emits for
//! a binary crate — so the world's `run` export lives in the SDK's rlib and appears in no source a
//! model reads. See [`compile`] for why the crate type is the whole trick.
//!
//! The surface a program calls is `packages/gg-sandbox-rust`'s SDK, reached through `--extern gg=…`
//! — which is packaging on the same terms a jar on a classpath is, and puts **no name** in a
//! program's own scope. A call is written in full (`gg::files::read_file(…)`) or under a line the
//! program wrote (`use gg::files;`, then `files::read_file(…)`). The surface is
//! **twelve capability modules** plus a thirteenth, `gg::core`, that declares no function and holds
//! the types every other module's signatures name; each module owns the types it produces, so
//! `gg::files::FileRead` is both the key a documentation view is opened by and a path a program can
//! write. Every call hands back `Result<_, core::ApiError>`, and optional arguments are a struct
//! with a `Default`. What that looks like in full is in
//! `apps/docs/src/content/docs/gg/languages/rust.md`.
//!
//! The library set is `std` plus the five crates `packages/gg-sandbox-rust/Cargo.toml` declares
//! under a `# --- heading ---`: `regex`, `serde_json`, `base64`, `itertools` and `indexmap`. Only
//! those and the SDK are named on `--extern`; the transitive closure under them is present, found
//! by `-L dependency=`, and not a name a program may write. The manifest carries the flag, the
//! catalogue's library list is reflected from the same headings, and a test compares the two before
//! compiling a program that uses all five — because a model told it may reach for something the
//! compile does not offer is a turn spent on gg's build.
//!
//! # How a failure reaches the model
//!
//! By **capture**, with nothing intercepted. There is no panic hook, no catch chain and no reporting
//! call anywhere in this arm's SDK: the program dies the way its runtime kills it and gg reads what
//! the runtime wrote.
//!
//! `wasm32-wasip1` is what buys that. It gives the guest a real standard error, which
//! [`membrane`](crate::sandbox) wires, so a panic arrives as `std`'s own sentence —
//! `thread 'main' (1) panicked at program.rs:6:5:` — in the model's own file at the model's own line
//! and column. A `main` returning `Err` has `std`'s `Termination` write `Error: …` before the shell
//! propagates the status, and an explicit `std::process::exit` is `proc_exit`, which reaches gg as
//! an `I32Exit`. `packages/gg-sandbox-rust/rust-version.sh` carries the measurement behind the
//! target.
//!
//! # And a code module is **linked**, which is why the seam hands a program its modules
//!
//! A code [skill](crate::skills)'s or [memory](crate::memories)'s Rust is a **crate of its own**,
//! built into an `.rlib` and named to the program's compiler on `--extern <key>=…` — the same
//! packaging the SDK arrives by, and it puts no name in the program's scope. The model writes
//! `csv_tools::parse(…)`, or a `use csv_tools::parse;` of its own, and gg writes nothing into the
//! program. On every arm before this one the binding is made at *run time*: the guest is handed each
//! module's prepared source beside the program and evaluates it first. Rust has no such moment, so
//! the seam hands [`prepare_program`](super::ProgramLanguage::prepare_program) the modules in scope
//! and this arm compiles them.
//!
//! The consequence a model can see is that `csv_tools::parse` is a **path** rather than a property
//! lookup: a key or a name that does not exist is a diagnostic on the turn that wrote it, where an
//! interpreted arm finds out when the call is reached.
//!
//! A module is compiled **twice**, and that is deliberate rather than an oversight — once alone at
//! the read, and once inside every preparation that links it, because a workspace belongs to one
//! preparation and the `.rlib` goes with it. The first compile is what puts a module author's
//! diagnostic at the read instead of against somebody else's program two turns later. See
//! [`compile::compile_module`] and [`compile`] for what the rebuild costs.


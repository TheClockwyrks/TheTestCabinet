/// This arm's catalogue, reflected out of the SDK's own rustdoc by
/// `packages/gg-sandbox-rust/signatures.sh` — `rustdoc`'s own JSON, read by `tools/signatures.py`.
///
/// It is not committed. `crates/gg/build.rs` runs that reflection as a step of building this
/// crate and this line embeds what it wrote into the build's own `OUT_DIR`, so what a model is
/// told about this arm is reflected out of the SDK sources in this checkout, on the build that
/// compiles the module telling it.
const SIGNATURES: &str = include_str!(concat!(env!("OUT_DIR"), "/signatures/rust.signatures.json"));

/// The parsed catalogue, parsed once per process.
static CATALOGUE: OnceLock<SignatureCatalogue> = OnceLock::new();

/// The one instance of this language. A unit struct, so the `static` costs nothing and coerces
/// straight to `&'static dyn ProgramLanguage`.
pub(super) static RUST: Rust = Rust;

/// Rust: compiled by `rustc` into the wasm component that evaluates it, per turn.
pub(super) struct Rust;

impl ProgramLanguage for Rust {
    fn id(&self) -> GgProgramLanguage {
        GgProgramLanguage::Rust
    }

    fn display_name(&self) -> &'static str {
        GgProgramLanguage::Rust.display_name()
    }

    /// **`::`** — the one arm that does not write `.`, because here a capability module is a Rust
    /// **module** and reaching a function in one is a path rather than a field access.
    ///
    /// It is the difference between a prompt full of `gg::views::open_text` and a prompt full of
    /// `gg::views.open_text`, which on this arm is `E0423: expected value, found module` — so a
    /// model would be taught, in every sentence gg writes about a call, a spelling that cannot
    /// compile.
    fn member_separator(&self) -> &'static str {
        "::"
    }

    /// One `rustc` over the entry file, the modules in scope and the embedded library set, then an
    /// in-process component encode — see [`compile`] for what it costs, what it shares, and how it
    /// tells a program `rustc` refused from a `rustc` that could not run.
    fn prepare_program(
        &self,
        source: &str,
        modules: &[CodeModule],
        context: &PrepareContext,
    ) -> Result<PreparedProgram, PrepareFailure> {
        compile::compile_program(source, modules, context)
    }

    /// `rustc`, which is what a Rust programmer calls the compiler and what its own binary is
    /// called.
    ///
    /// Not `wit-component`, which encodes the module `rustc` emitted into a component and judges
    /// nothing about the program: the same reason the JVM arms name their front end rather than
    /// TeaVM. Naming a checker is also what has this arm's compile
    /// [recorded](crate::sandbox::SandboxOutcome::compile) on every turn, the failing path included
    /// — which matters more here than anywhere, since this is the arm where the compile *is* the
    /// artifact.
    fn checker(&self) -> Option<&'static str> {
        Some("rustc")
    }

    /// Unpack the embedded library set now, so the first code turn does not.
    ///
    /// The whole of this arm's warm-up, and the smallest of any compiled arm's: there is no daemon
    /// to start and no compiler to load, because `rustc` is a one-shot process whose cost is the
    /// compile rather than the start-up. Idempotent and best effort — a failure here is the failure
    /// the first compile makes, and there it is classified, counted and reported as a
    /// [toolchain failure](PrepareFailure::Toolchain).
    fn warm_prepare(&self) {
        compile::warm();
    }

    /// The module's own `rustc`, asked for metadata rather than an artifact — and the names its
    /// namespace offers, read from the author's own source.
    ///
    /// What comes back is **source**, which is what a linked language's module has to be: it is an
    /// input to the [program compile](compile::compile_program) that binds it, not something a guest
    /// could load on its own.
    fn prepare_module(
        &self,
        source: &str,
        context: &PrepareContext,
    ) -> Result<PreparedModule, PrepareFailure> {
        compile::compile_module(source, context)
    }

    /// `.rs`, and nothing else. Nothing else in the registry compiles Rust.
    fn module_file_extensions(&self) -> &'static [&'static str] {
        &["rs"]
    }

    /// [snake_case](self::binding_name) — Rust's own convention for a name a program writes, and
    /// this SDK's for every function it binds.
    fn binding_name(&self, name: &str) -> String {
        binding_name(name)
    }

    /// **`<key>::<name>`** — a path rooted at the module's own crate, because that is what a module
    /// is here.
    ///
    /// The seam's default roots it at `lib`, which on this arm would name a crate nothing supplies.
    /// A module arrives on `--extern <key>=…`, exactly as gg's SDK arrives on `--extern gg=…`, so
    /// the key is the first segment a program writes and there is nothing above it.
    fn lib_access(&self, key: &str) -> String {
        format!("{key}{}{}", self.member_separator(), super::LIB_ACCESS_NAME)
    }

    /// **None**, because this arm reaches gg's own SDK with no line either.
    ///
    /// `--extern` puts a crate in the **extern prelude**, which makes the name reachable and puts
    /// nothing in the program's own scope: `csv_tools::parse(…)` resolves from a program's first
    /// line, exactly as `gg::files::read_file(…)` does. A program that would rather write
    /// `use csv_tools::parse;` first may, and that line is the program's own choice rather than
    /// something the surface requires of it — quoting one here would tell a model a line is needed
    /// when none is.
    fn lib_import(&self, _key: &str) -> Option<String> {
        None
    }

    /// **None.** This arm has no guest component, because the component *is* the program: see this
    /// module's own documentation, and [`PreparedProgram::component`].
    fn guest_component(&self) -> Option<&'static [u8]> {
        None
    }

    /// This language's catalogue, parsed once and checked to be **this** language's.
    ///
    /// Every registered language's build reflects one of these under its own stem into the one
    /// `OUT_DIR`, and each carries the language it was generated for; checking it here is what stops
    /// a catalogue written — or embedded — under the wrong stem from reaching a model as a system
    /// prompt describing a sandbox nobody has.
    fn catalogue(&self) -> &'static SignatureCatalogue {
        CATALOGUE.get_or_init(|| {
            let catalogue = SignatureCatalogue::parse(SIGNATURES)
                .expect("the generated signature catalogue is valid JSON of the expected shape");
            assert_eq!(
                catalogue.language,
                GgProgramLanguage::Rust,
                "`signatures/rust.signatures.json` was generated for another program language",
            );
            catalogue
        })
    }

    /// [`gg::views::open_file("src/main.rs", …)?;`](self::open_file_statement) — with the window
    /// as two of the three fields of this arm's options struct.
    fn open_file_statement(&self, path: &str, window: Option<FileWindow>) -> String {
        open_file_statement(&spell(self, VIEWS_OPEN_FILE), path, window)
    }

    /// [The `fn main` those calls live in](self::open_file_program), which is what a statement list
    /// is not on this arm.
    ///
    /// A model reads this out of its own transcript as an example of its own output, and a Rust file
    /// has nowhere for a statement to live outside a function — so a statement list would be
    /// teaching a shape `rustc` answers with `error[E0601]: main function not found`.
    fn open_file_program(&self, views: &[(&str, Option<FileWindow>)]) -> String {
        open_file_program(&spell(self, VIEWS_OPEN_FILE), views)
    }

    /// [An array of names and a `for` over it](self::open_docs_views_statement), each iteration
    /// opening one documentation view — inside the `fn main` this language has nowhere else to put
    /// a statement than.
    fn open_docs_views_statement(&self, names: &[&str]) -> String {
        open_docs_views_statement(&spell(self, VIEWS_OPEN_DOCS_VIEW), names)
    }

    /// [One `fn main` holding one search, one array and one `for` loop, each call composed with
    /// `?`](self::bootstrap_program), with both paths resolved from this language's own catalogue.
    fn bootstrap_program(&self, modules: &[&str], docs: &[&str]) -> String {
        bootstrap_program(
            &spell(self, DOCS_SEARCH),
            &spell(self, VIEWS_OPEN_DOCS_VIEW),
            modules,
            docs,
        )
    }

    /// One `pub fn` returning `name` — because this arm's module shape is not its program shape.
    ///
    /// A program here is a whole binary crate and a module is a **file of items**: the seam's default
    /// subject is this language's generated documentation program, which declares `fn main`, and a
    /// code module that declared one would be an entry point in a file nothing runs. The `name`
    /// rides in as a returned **string literal**, which is where the module's one export hands it
    /// back.
    #[cfg(test)]
    fn gate_module(&self, name: &str) -> String {
        format!(
            "pub fn marker() -> &'static str {{
    {}
}}
",
            serde_json::Value::String(name.to_string())
        )
    }
}


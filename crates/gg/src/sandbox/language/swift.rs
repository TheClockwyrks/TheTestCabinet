//! **Swift** — the second arm whose component is compiled **per turn**, and the only one whose
//! program is compiled *verbatim*.
//!
//! Everything this arm owns lives here or in one of this module's siblings:
//!
//! * [`compile`] — the host-side `swiftc`, the in-process component encode with the preview1
//!   adapter, what they cost, what they share, and the two failures they tell apart;
//! * [`source`] — the one thing gg writes, which is not a wrapper around a program but the
//!   namespace a **code module**'s declarations are moved into, in place;
//! * [`healing`] — the [dialect](crate::healing::Dialect) response healing asks its lexical
//!   questions of, whose lexer is also what reads a code module's top level;
//! * [`PROMPT`] — the responses-as-code system prompt and the "nothing shown" notice, both written
//!   in Swift's syntax;
//! * `packages/gg-sandbox-swift/` — the SDK a program calls, the shell it is compiled beside, the
//!   curated library set, and the build that cuts them;
//! * `swift.guest.tar.gz`, `swift.libraries.tar.gz`, `swift.adapter.wasm` and
//!   `swift.toolchain.json` — the compile inputs, the library set, the adapter, and what built them,
//!   generated by `crates/gg-sandbox-artifacts/swift` into this build's own `OUT_DIR` rather than
//!   committed anywhere, and reached through `GG_ARTIFACTS_SWIFT`;
//! * the **signature catalogue**, which is the whole of what a model is told about this surface —
//!   reflected out of the SDK's own documentation comments and generated into this build's
//!   `OUT_DIR` rather than committed anywhere (see `crates/gg/build.rs`).
//!
//! # What a Swift program calls, and how it is in scope
//!
//! The surface is divided into **thirteen capability modules**, and each is a caseless `enum` —
//! Swift's own namespace inside a module — so `files.readFile("src/main.swift")` is a call on a
//! namespace and nothing is constructed first. A caseless `enum` rather than that many real Swift
//! modules behind an `@_exported` umbrella: the umbrella was measured and does re-export
//! transitively, but a module of its own would have to be called `GgFiles` where the whole scheme's
//! vocabulary is `files`, and a program whose own `let files` shadowed it would be shadowing the
//! same name either way. The fully qualified `gg.files.readFile` is the escape from that shadowing,
//! and it is a real path a program may write, which is why it is the name this arm catalogues.
//!
//! Every call **throws**, so `try` is the whole of the ceremony and a failure is an ordinary Swift
//! `Error` a `catch` branches on. Optional arguments are **default values**, required ones are
//! positional, and everything whose role the function's name does not already carry has an
//! **argument label** — `files.editFile("a", replacing: "x", with: "y")`,
//! `delegation.sendMessage("note", to: id)`. A value a call hands back may carry the call that
//! belongs to it: `handle.send(…)`, `view.close()`, `hit.read()`.
//!
//! It is in scope with **no import line**, and that is what lets the reply stay verbatim. The SDK is
//! compiled ahead of time into a module called `gg`, and gg's shell — a second file of the model's
//! own module — writes `@_exported import gg`. A plain `import` is file-scoped and would put nothing
//! in `main.swift`; a re-export is module-scoped, so the model's file opens with the whole surface
//! already there. A separate module is also what makes the SDK **shadowable**: a program that
//! declares its own `files` or its own `DirEntry` wins, where source compiled into the program's own
//! module would be a redeclaration error on the model's own line.
//!
//! The library set is the Swift standard library, the modules the Swift SDK for WebAssembly ships
//! (Foundation and its companions, `RegexBuilder`, `Synchronization`, `Observation`, `WASILibc`) and
//! three vendored packages — swift-collections, swift-algorithms and swift-numerics — compiled into
//! one static archive. A static archive is why they cost nothing: the linker pulls members, so an
//! artifact for a program that imports none of them is byte for byte the size of one built without
//! the archive at all. `packages/gg-sandbox-swift/libraries.txt` is the one declaration, and
//! `swift.surface.test.rs` compiles a program that imports every module in it.
//!
//! # Why this arm has no guest component
//!
//! For the reason [Rust](super::rust) has none. Every arm before those two evaluates a **string**:
//! Python's baked component holds a whole CPython, Ruby's holds Opal, the ECMAScript one holds
//! a JavaScript engine, and a program crosses the membrane as source those runtimes read. `swiftc`
//! does not produce a Swift interpreter that later runs a program; it produces the program, and
//! that module *is* the component. There is no artifact of this language that is not one particular
//! program, so there is nothing to bake and nothing a per-process cache could hold.
//!
//! # What a Swift program is, here
//!
//! **The model's reply, unaltered, as a top-level Swift file.** Not a function body, not a
//! declaration list, and not anything gg wrapped: the bytes the model wrote are the bytes `swiftc`
//! reads, so a diagnostic at line 7 is line 7 and there is no offset to subtract anywhere in this
//! arm.
//!
//! That is forced rather than chosen. Swift refuses `extension`, `protocol` and `import` inside a
//! function body, so the wrapper the Rust arm uses — and that every statement-shaped arm before it
//! uses — would forbid three things a Swift author writes without thinking, one of which
//! (`extension`) is what the language is built around. A top-level file is the only Swift context
//! that admits declarations and bare statements together.
//!
//! What makes it work is that gg's shell is a second file of the **same module**: Swift lowers a
//! top-level file's statements into the target's C entry point, and the shell, sharing the module,
//! names that symbol and calls it from the `run` export. See [`compile`].
//!
//! # What this arm has that no other does
//!
//! A guest whose failures **cannot be caught by anything inside it**. The Rust arm has no unwinder
//! either, but it has a panic *hook* — a function that runs on a live guest before the abort and
//! can complete an ordinary `feedback.report-error` first. Swift has no equivalent, and its
//! top-level code is not a `throws` context a shell can wrap, so an uncaught error, a `fatalError`,
//! a force-unwrapped `nil`, an index out of range and an arithmetic overflow all end as a **trap**.
//!
//! What keeps those from being opaque is not what anyone would guess. Swift at `-Osize` does not
//! *print* its runtime failures: the optimiser replaces the report with a bare `unreachable` and
//! encodes the message in the **debug information**, as the name of a synthetic inlined frame. So
//! the artifact is compiled with `-g`, gg's engine symbolicates a trap's frames, and a model reads
//!
//! ```text
//! Swift runtime failure: Index out of range
//!   … at /gg/work/main.swift:3:22
//! ```
//!
//! — the message and its own line, for a failure it could not have caught. Without the debug
//! information the same program says `program.wasm!main` and nothing else. See
//! [`compile::DEBUG_INFO`](self::compile) for the measurement, and for what those sections record
//! about the environment they were produced in.
//!
//! One failure is the exception and is worth naming, because it is the opposite of the one above:
//! an **uncaught throw** arrives with gg's own sentence and *no line at all*. The runtime hands the
//! error to `swift_errorInMain` from the entry point's synthesized epilogue, so the only frames left
//! are `/<compiler-generated>` and there is nothing to symbolicate. Catching what you expect is what
//! buys the line back. Measured in `swift.surface.test.rs`.
//!
//! # And a code module is **linked**, which is why the seam hands a program its modules
//!
//! A code [skill](crate::skills)'s or [memory](crate::memories)'s namespace is bound at `lib.<key>`
//! for every program the agent writes afterwards. On every interpreted arm that binding is made at
//! *run time*: the guest is handed each module's prepared source beside the program and evaluates it
//! first. Swift has no such moment — a module is Swift, Swift links, and the only artifact a module
//! can end up in is the artifact of a program that was compiled against it.
//!
//! So the seam hands [`prepare_program`](super::ProgramLanguage::prepare_program) the modules in
//! scope, and each becomes a further file of the program's **own Swift module**, with its top-level
//! declarations moved into `lib.<key>` by being wrapped where they stand — see [`source`] for the
//! shape, for what it preserves that the two alternatives would have given up, and for the one
//! construct it refuses. The consequence a model can see is that `lib.csvTools.parse` is a **name
//! the compiler resolves** rather than a property looked up on a value: a key that does not exist
//! is a diagnostic on the turn that wrote it, where an interpreted arm finds out when the call is
//! reached.
//!
//! A module is compiled **twice**, and that is deliberate rather than an oversight — once alone when
//! it is read, only to be checked, and once as part of every program that uses it. Without the first
//! compile, a module that does not build would take down every program the agent wrote from then on,
//! with the diagnostic landing against the turn's own program in a file the model never saw. See
//! [`compile::compile_module`].


/// This arm's catalogue, reflected out of the SDK's own documentation comments by
/// `packages/gg-sandbox-cpp/signatures.sh` — `clang++ -ast-dump=json`, which is clang's own comment
/// parser and the machinery `-Wdocumentation` and `clang-doc` are built on.
///
/// It is not committed. `crates/gg/build.rs` runs that reflection as a step of building this
/// crate and this line embeds what it wrote into the build's own `OUT_DIR`, so what a model is
/// told about this arm is reflected out of the SDK sources in this checkout, on the build that
/// compiles the module telling it.
const SIGNATURES: &str = include_str!(concat!(env!("OUT_DIR"), "/signatures/cpp.signatures.json"));

/// The parsed catalogue, parsed once per process.
static CATALOGUE: OnceLock<SignatureCatalogue> = OnceLock::new();

/// The one instance of this language. A unit struct, so the `static` costs nothing and coerces
/// straight to `&'static dyn ProgramLanguage`.
pub(super) static CPP: Cpp = Cpp;

/// C++: compiled by `clang++` into the wasm component that evaluates it, per turn.
pub(super) struct Cpp;

impl ProgramLanguage for Cpp {
    fn id(&self) -> GgProgramLanguage {
        GgProgramLanguage::Cpp
    }

    fn display_name(&self) -> &'static str {
        GgProgramLanguage::Cpp.display_name()
    }

    /// **`::`** — the second arm that does not write `.`, because here a capability module is a
    /// **namespace** and reaching a function in one is a qualified name rather than a member
    /// access.
    ///
    /// It is the difference between a prompt full of `gg::views::open_text` and a prompt full of
    /// `view.open_text`, which on this arm is *no member named 'open_text' in the global namespace*
    /// — so a model would be taught, in every sentence gg writes about a call, a spelling that
    /// cannot compile.
    fn member_separator(&self) -> &'static str {
        "::"
    }

    /// One `clang++` over the model's file and the code modules in scope, then an in-process
    /// component encode — see [`compile`] for what it costs, what it shares, and how it tells a
    /// program `clang++` refused from a `clang++` that could not run.
    fn prepare_program(
        &self,
        source: &str,
        modules: &[CodeModule],
        context: &PrepareContext,
    ) -> Result<PreparedProgram, PrepareFailure> {
        compile::compile_program(source, modules, context)
    }

    /// `clang++`, which is what a C++ programmer calls the compiler and what the binary gg spawns is
    /// called.
    ///
    /// Not `wit-component`, which encodes the module `clang++` linked into a component and judges
    /// nothing about the program: the same reason the [Rust](super::rust) and [Swift](super::swift)
    /// arms name their front ends and the JVM arms name theirs rather than TeaVM. Naming a checker
    /// is also what has this arm's compile [recorded](crate::sandbox::SandboxOutcome::compile) on
    /// every turn, the failing path included — which matters here because this arm's compile is the
    /// cheapest of the three that produce their own artifact, and an arm that looks free and is not
    /// is exactly what the seam requires a language to declare rather than leave to be inferred.
    fn checker(&self) -> Option<&'static str> {
        Some("clang++")
    }

    /// Unpack the embedded guest archive now, so the first code turn does not.
    ///
    /// The whole of this arm's warm-up, and the whole of what it could be: 32 KB decompressed, once
    /// per machine. Nothing is compiled ahead of a program, because nothing is put in front of one —
    /// every header a compile parses is one the program itself included. Idempotent and best effort:
    /// a failure here is the failure the first compile makes, and there it is classified, counted
    /// and reported as a [toolchain failure](PrepareFailure::Toolchain).
    fn warm_prepare(&self) {
        compile::warm();
    }

    /// The module's own `clang++`, asked to precompile the interface a program imports — and the
    /// names its namespace offers, read from the author's own source.
    ///
    /// What comes back is **source**, which is what a linked language's module has to be: it is an
    /// input to the [program compile](compile::compile_program) that binds it, not something a guest
    /// could load on its own.
    fn prepare_module(
        &self,
        key: &str,
        source: &str,
        context: &PrepareContext,
    ) -> Result<PreparedModule, PrepareFailure> {
        compile::compile_module(key, source, context)
    }

    /// **`import lib.<key>;`** — the line a program writes to reach a code module's namespace, and
    /// the only thing that puts `lib` in scope.
    ///
    /// A module in scope is [precompiled](self::compile::compile_module) into an interface of its own
    /// and named to the compile with `-fmodule-file=`, which says where the module is and declares
    /// nothing, exactly as `-I` says where gg's headers are. So this line is the model's to write,
    /// on the same terms as the `#include <gg/files.hpp>` that reaches gg's surface, and a program
    /// that omits it earns clang's own *use of undeclared identifier 'lib'*.
    ///
    /// It names the [module](source::module_name) rather than the namespace, because that is what an
    /// import declaration resolves: a key of `module` is imported as `import lib.Module;` and
    /// written `lib::module::<name>`.
    fn lib_import(&self, key: &str) -> Option<String> {
        Some(source::module_import(key))
    }

    /// **`.hpp`, and nothing else.**
    ///
    /// What a skill author's C++ file is called. A code module's declarations are what a program
    /// links against rather than a translation unit of their own, which is what a header holds, and
    /// `.hpp` is the extension C++ uses for one when it means C++ rather than C. gg compiles the
    /// file as a [named module](compile::compile_module) of its own and that is gg's
    /// business rather than the author's.
    ///
    /// One rather than the several a C++ author might reach for (`.h`, `.hh`, `.hxx`), because the
    /// seam's reason for the list being a list does not apply here: it is for two languages that
    /// share a module runtime, where withholding a skill from one of them would be a difference
    /// between the arms larger than the one a study of the pair is measuring. Nothing else in the
    /// registry compiles C++, so there is no such pair and no such loss — and one spelling is one
    /// answer to "what does a skill's C++ file have to be called".
    fn module_file_extensions(&self) -> &'static [&'static str] {
        &["hpp"]
    }

    /// [snake_case](self::binding_name) — what this SDK spells every function and every type in, and
    /// what the standard library it arrives beside spells everything in.
    fn binding_name(&self, name: &str) -> String {
        binding_name(name)
    }

    /// **None.** This arm has no guest component, because the component *is* the program: see this
    /// module's own documentation, and [`PreparedProgram::component`].
    fn guest_component(&self) -> Option<&'static [u8]> {
        None
    }

    /// This language's catalogue, parsed once and checked to be **this** language's.
    ///
    /// Every registered language's build reflects one of these under its own stem into the one
    /// `OUT_DIR`, and each carries the language it was generated for; checking it here is what stops
    /// a catalogue written — or embedded — under the wrong stem from reaching a model as a system
    /// prompt describing a sandbox nobody has.
    fn catalogue(&self) -> &'static SignatureCatalogue {
        CATALOGUE.get_or_init(|| {
            let catalogue = SignatureCatalogue::parse(SIGNATURES)
                .expect("the generated signature catalogue is valid JSON of the expected shape");
            assert_eq!(
                catalogue.language,
                GgProgramLanguage::Cpp,
                "`signatures/cpp.signatures.json` was generated for another program language",
            );
            catalogue
        })
    }

    /// [`gg::views::open_file("src/main.cpp");`](self::open_file_statement) — with the window as the
    /// call's own optional second argument, written as a designated initialiser.
    fn open_file_statement(&self, path: &str, window: Option<FileWindow>) -> String {
        open_file_statement(&spell(self, VIEWS_OPEN_FILE), path, window)
    }

    /// [The include the call needs and the `int main` it lives in](self::open_file_program), which
    /// is what a statement list is not on this arm.
    ///
    /// The one arm that has to override the seam's default twice over: C++ has nowhere for a bare
    /// statement to live, and gg's surface is undeclared until a line the program wrote declares it.
    /// A model reads this out of its own transcript as an example of its own output, so a text it
    /// could not have sent would be teaching a shape its next reply is refused for.
    fn open_file_program(&self, views: &[(&str, Option<FileWindow>)]) -> String {
        open_file_program(
            &includes(self, &[VIEWS_OPEN_FILE]),
            &spell(self, VIEWS_OPEN_FILE),
            views,
        )
    }

    /// [An array of names and a range `for` over it](self::open_docs_views_statement), each
    /// iteration opening one documentation view — inside the `int main` this language has nowhere
    /// else to put a statement than, under the `#include` that declares the call and the ones that
    /// declare the standard-library types it holds the names in.
    fn open_docs_views_statement(&self, names: &[&str]) -> String {
        open_docs_views_statement(
            &includes(self, &[VIEWS_OPEN_DOCS_VIEW]),
            &spell(self, VIEWS_OPEN_DOCS_VIEW),
            names,
        )
    }

    /// [One `int main` holding one search and one range `for`](self::bootstrap_program), under the
    /// `#include` lines that declare the calls it makes — every one of them resolved from this
    /// language's own catalogue — and the ones that declare `std::array` and `std::string_view`.
    ///
    /// The lines are resolved for the calls the program really writes rather than for the two this
    /// seam knows about: an agent holding neither `files` nor `shell` is handed no modules and gets
    /// [no search at all](self::bootstrap_program), and an `#include` for a header nothing in the
    /// program names is a habit a model reads out of its own transcript.
    fn bootstrap_program(&self, modules: &[&str], docs: &[&str], tree: Option<u32>) -> String {
        let mut made: Vec<crate::sandbox::OperationId> = Vec::new();
        if tree.is_some() {
            made.push(FILES_TREE);
            made.push(VIEWS_OPEN_TEXT);
        }
        if !modules.is_empty() {
            made.push(DOCS_SEARCH);
        }
        made.push(VIEWS_OPEN_DOCS_VIEW);
        bootstrap_program(
            BootstrapCalls {
                includes: &includes(self, &made),
                search: &spell(self, DOCS_SEARCH),
                open_docs_view: &spell(self, VIEWS_OPEN_DOCS_VIEW),
                tree_call: &spell(self, FILES_TREE),
                open_text: &spell(self, VIEWS_OPEN_TEXT),
            },
            modules,
            docs,
            tree,
        )
    }

    /// One function returning `name` — because a C++ code module is a file of **declarations** and a
    /// C++ program is a translation unit that must define `main`.
    ///
    /// The seam's default subject is this language's generated documentation program, and that
    /// program *would* compile as a module: a `main` inside `namespace lib::<key>` is an ordinary
    /// function rather than an entry point. It is still the wrong subject, because it would be
    /// asserting isolation over a shape no code skill anyone writes has. So this arm answers for
    /// itself, as [Rust](super::rust), [Swift](super::swift) and the [JVM](super::jvm) arms do, and
    /// the `name` rides in as a returned **string literal** — which is where the module's one export
    /// hands it back.
    ///
    /// It writes its own `#include <string>`, which is what a skill author writes and what gg
    /// [hoists](self::source::namespaced) into the module's global module fragment: nothing is in
    /// front of a module either.
    #[cfg(test)]
    fn gate_module(&self, name: &str) -> String {
        format!(
            "#include <string>\n\nstd::string marker() {{\n  return {};\n}}\n",
            serde_json::Value::String(name.to_string())
        )
    }
}


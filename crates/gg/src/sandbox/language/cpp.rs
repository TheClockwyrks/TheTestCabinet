//! **C++** — the third arm whose component is compiled **per turn**, and the second whose program
//! is compiled *verbatim*.
//!
//! Everything this arm owns lives here or in one of this module's siblings:
//!
//! * [`compile`] — the host-side `clang++`, the in-process component encode with the preview1
//!   adapter, what they cost, what they share, and the two failures they tell apart;
//! * [`source`] — the one thing gg reads out of a reply, which is whether it defines `main`, and
//!   what it writes around a **code module**: the named module and namespace its declarations are
//!   opened inside, with the author's own `#include` lines hoisted above them;
//! * [`mask`] — the byte-level scan [`source`] reads;
//! * `packages/gg-sandbox-cpp/Sources/sdk/` — the SDK, hand-written and idiomatic, whose `///`
//!   comments are the model-facing documentation and whose `//` comments are not;
//! * `packages/gg-sandbox-cpp/signatures.sh` — the reflection, out of clang's own comment AST;
//! * `cpp.guest.tar.gz`, `cpp.adapter.wasm` and `cpp.toolchain.json` — the compile inputs, the
//!   adapter, and what built them, generated by `crates/gg-sandbox-artifacts/cpp` into this build's
//!   own `OUT_DIR` rather than committed anywhere, and reached through `GG_ARTIFACTS_CPP`;
//! * the **signature catalogue** that reflection emits, which is the whole of what a model is told
//!   about this surface — generated into this build's `OUT_DIR` rather than committed anywhere (see
//!   `crates/gg/build.rs`).
//!
//! # What the surface looks like, and the one thing a model has to know about it
//!
//! **Every capability module is a `namespace` inside `namespace gg`, with the types it produces
//! nested in it, and one header per module** — so a program writes `#include <gg/files.hpp>` and
//! then `gg::files::read_file(…)`, which is the line the module's own catalogue entry states and
//! the call written in full.
//!
//! Nothing gg passes the compiler puts any of it in scope. The header is on the include path and the
//! bodies are in the `sdk.o` every artifact links, which is
//! [packaging](https://docs.testcabinet.ai/gg/responses-as-code/invariants/); the declaration is the
//! model's own `#include`. **The C++ standard library arrives the same way**: nothing is put in
//! front of a program, so `std::vector` is undeclared until the reply writes `#include <vector>`.
//! There is no using-directive anywhere either — so a program that declares its own
//! `namespace files` has taken a name gg was not using, and `gg::files::` goes on resolving beside
//! it.
//!
//! The nesting is what makes the full name a real C++ path rather than a label, which is the whole
//! point of the surface being modules: it is what a search hit shows, what a documentation view is
//! opened by, and what lets two modules each declare a `close`. `Sources/prelude.hpp` is where the
//! library set a program may reach for is declared — by the file, not in front of the program — and
//! it records the reason `<filesystem>` is off that set.
//!
//! Everything else is spelling, and it is written to read like the standard library it arrives
//! beside: `snake_case` throughout, `enum class` for a fixed choice, aggregates with public members
//! for a record, `std::variant` for a value that is one of two things, a **default argument** for
//! one optional part and a **designated initialiser** for several, and a thrown `gg::core::api_error` —
//! a `std::runtime_error` — for a call that failed.
//!
//! # Why this arm has no guest component
//!
//! For the reason [Rust](super::rust) and [Swift](super::swift) have none. Every arm before those
//! three evaluates a **string**: Python's baked component holds a whole CPython, Ruby's holds
//! Opal, the ECMAScript one holds a JavaScript engine, and a program crosses the membrane as source
//! those runtimes read. `clang++` does not produce a C++ interpreter that later runs a program; it
//! produces the program, and that module *is* the component. There is no artifact of this language
//! that is not one particular program, so there is nothing to bake and nothing a per-process cache
//! could hold.
//!
//! # What a C++ program is, here
//!
//! **The model's reply, unaltered, as a translation unit that defines `main`.** Not a function body
//! and not anything gg wrapped: the bytes the model wrote are the bytes `clang++` reads, so a
//! diagnostic at line 7 is line 7 and there is no offset to subtract anywhere in this arm.
//!
//! That is forced rather than chosen, and C++ forces it harder than Swift did. A function-body
//! wrapper would refuse a `template`, which may not be declared at block scope at all and is most of
//! what generic C++ is; a `namespace`, for the same reason; and a `#include`, which would still
//! *expand* and would expand the whole of `<vector>` inside a function body. A translation unit is
//! the only C++ context that admits all three.
//!
//! The price is the one refusal this arm has, and it is the exact inverse of the
//! [Rust](super::rust) arm's. Rust has no `main` and refuses a program that defines one. C++ has
//! nowhere for a bare statement to live, so a reply that defines **no** `main` is a program with
//! nothing to run — and gg refuses it by name, at prepare time, rather than letting it link. That
//! `wasm-ld` links one at all is the surprising half and is measured rather than assumed: wasi-libc
//! references `main` **weakly**, so the missing entry point resolves to a stub that traps and the
//! compiler exits zero. See [`source`] for why no linker flag asks the question and why gg's
//! lexical answer can only be wrong in the safe direction.
//!
//! # What this arm has that no other does
//!
//! **A real exception mechanism.** [Rust](super::rust) aborts and reaches for a panic hook;
//! [Swift](super::swift) traps and has no hook at all. C++ here has `throw`, `try` and `catch`, and
//! they work — `-fwasm-exceptions` with the standardised encoding, against a wasmtime configured to
//! accept it. What that cost the workspace is written down in [`compile`] rather than quietly
//! absorbed: wasmtime's exception support is behind a build feature that the two other wasm hosts
//! in this repository now also build with, and both pin their own validation surface back
//! explicitly rather than inheriting a wider one.
//!
//! # What this arm has that is worse than any other, and cannot be engineered away
//!
//! **A failure that says nothing.** Three of the four ways a C++ program fails here carry their own
//! words, and each takes a decision to get there. An uncaught `throw` is caught by gg's shell and
//! reported as an ordinary model-facing error carrying the exception's own class and `what()` —
//! without which it would be a bare `thrown Wasm exception`, since an exception escaping `main`
//! under `-fwasm-exceptions` never reaches `std::terminate`. A libc++ **hardening** check —
//! `v[10]`, `.front()` on an empty container — carries libc++'s own sentence *and* the model's own
//! line, out of the artifact's debug information, and only because gg turns hardening on: wasi-sdk
//! ships libc++ configured to check nothing. A non-zero status returned from `main` is read by that
//! same shell and reported with the number the program chose, which is the one failure channel C++
//! gives an entry point and the one that walks past every `catch` there is.
//!
//! The fourth is undefined behaviour, and it arrives as a bare trap: an integer division by zero, a
//! pointer past the end of an array. `-g1` locates it at the model's own line and that is all
//! anything can do. A dereferenced null is worse still and is not a trap at all: address zero is
//! ordinary linear memory on this target, so reading and writing through a null pointer succeeds and
//! the turn is recorded a success.
//!
//! It is worth stating plainly because it is a **comparability** risk rather than only a usability
//! one: on this arm, and on no other here, a failure caused by the language can be hard to tell in
//! the run record from a model that reasoned badly. A study reading this arm beside the others has
//! to know that — and hardening is what keeps the most common shape of it, an out-of-bounds
//! container access, out of that band and in the one above.
//!
//! # And a code module is **linked**, which is why the seam hands a program its modules
//!
//! A code [skill](crate::skills)'s or [memory](crate::memories)'s namespace is `lib::<key>`, and a
//! program reaches it by writing [`import lib.<key>;`](ProgramLanguage::lib_import). On every
//! interpreted arm the module is a value the guest is handed beside the program and evaluates first.
//! C++ has no such moment — a module is C++, C++ links, and the only artifact a module can end up in
//! is the artifact of a program that was compiled against it.
//!
//! So the seam hands [`prepare_program`](super::ProgramLanguage::prepare_program) the modules in
//! scope, and each becomes a named C++ module **the program imports itself**, with its declarations
//! opened inside `namespace lib::<key>` **where they stand**. It is the plainest shape of the three
//! compiled arms — C++ has a real nested namespace, so nothing has to be re-synthesized or declared
//! twice — and the one thing that had to be decided is what happens to a `#include` at a module's
//! top level, which is **hoisted** into the module's global module fragment, where an author's own
//! headers reach the module and nobody who imports it. gg writes the one include that declares its
//! own surface into that same fragment, which is the wrapper
//! [a module is allowed and a program is not](https://docs.testcabinet.ai/gg/responses-as-code/invariants/):
//! a module is a skill author's file that gg wraps, where a program is a model's reply that gg does
//! not touch. See [`source`] for the shape, the hoist and the argument.
//!
//! What a model can see of the difference is that `lib::csv_tools::parse` is a **name the compiler
//! resolves** rather than a property looked up on a value: a key that does not exist, and a module
//! the program forgot to import, are both a diagnostic on the turn that wrote it, where an
//! interpreted arm finds out when the call is reached.
//!
//! A module is compiled **twice**, and that is deliberate rather than an oversight — once alone when
//! it is read, only to be checked, and once as part of every program that uses it. Without the first
//! compile, a module that does not build would take down every program the agent wrote from then on,
//! with the diagnostic landing against the turn's own program in a file the model never saw. See
//! [`compile::compile_module`].


/// **The `#include` lines a program writes to reach the calls it makes**, one per module, in the
/// order the calls are listed and each written once — followed by the blank line a C++ author leaves
/// between a preamble and the code.
///
/// Resolved out of this arm's own catalogue rather than written out, for the reason [`spell`]
/// resolves a call's name: the catalogue is where a module's [import line](crate::sandbox::ModuleView::import)
/// is composed, a model reads that same line in its own module list, and a second copy here would be
/// the one that drifts. A module that states no line contributes none, which is a state this arm's
/// catalogue never reaches and every other arm's does.
fn includes(language: &dyn ProgramLanguage, calls: &[crate::sandbox::OperationId]) -> String {
    let functions = crate::sandbox::catalogue_functions(language);
    let modules = crate::sandbox::catalogue_modules(language);
    let mut lines: Vec<&str> = Vec::with_capacity(calls.len());
    for call in calls {
        let Some(function) = functions.iter().find(|function| {
            function.alias_of.is_none()
                && crate::sandbox::operation_of(function)
                    .is_some_and(|operation| operation.id == *call)
        }) else {
            continue;
        };
        let Some(line) = modules
            .iter()
            .find(|module| module.id == function.module)
            .and_then(|module| module.import)
        else {
            continue;
        };
        if !lines.contains(&line) {
            lines.push(line);
        }
    }
    match lines.is_empty() {
        true => String::new(),
        false => format!("{}\n\n", lines.join("\n")),
    }
}

/// **The `#include` lines a program gg synthesized writes for the standard library it uses**, above
/// the ones [`includes`] resolves for gg's own surface and separated from them by the blank line a
/// C++ author leaves between the two groups.
///
/// gg's own generated programs obey the rule a model's program obeys: nothing is put in front of a
/// translation unit, so a program that writes `std::array` includes `<array>` itself. It is not
/// decoration — without these lines every program in this file is *use of undeclared identifier
/// 'std'*, and one of them is compiled and run before the model's first request.
///
/// `<string_view>` only where it is really named. A list with entries deduces its `std::array` from
/// string literals, where an empty one has to spell the element type out
/// ([`open_docs_views_statement`] says why) — and a program carrying an include for a type it does
/// not use is a habit a model reads out of its own transcript.
fn standard_includes(names_an_empty_list: bool) -> String {
    match names_an_empty_list {
        true => "#include <array>\n#include <string_view>\n\n".to_string(),
        false => "#include <array>\n\n".to_string(),
    }
}

/// `csv-tools` → `csv_tools`, `my_helpers.v2` → `my_helpers_v2`, `9lives` → `_9lives`.
///
/// snake_case because that is what this SDK spells every function and every type in, and what the
/// standard library it arrives beside spells everything in — so a program reaching
/// `lib::csv_tools::parse(…)` reads like the rest of its own scope.
///
/// Any separator — `-`, `.`, or anything a name should not have had — becomes `_`, a run of them
/// becomes one, an upper-case letter is lowered, a name that is nothing but separators becomes
/// `module`, and a leading digit is prefixed.
///
/// It has to be a valid C++ **identifier** for the same reason the [Rust](super::rust) arm's does:
/// on this arm the key is a namespace the compiler resolves (`lib::<key>`) rather than a string
/// looked up at run time, so a key C++ could not parse would be a program that does not compile.
///
/// Deliberately ASCII-only, though C++ identifiers may carry other Unicode letters, for the reason
/// every other arm gives: a name a model has to reproduce exactly is one that should have no
/// characters it could get wrong.
pub(super) fn binding_name(name: &str) -> String {
    let mut out = String::new();
    let mut separated = false;
    for character in name.chars() {
        if character.is_ascii_alphanumeric() {
            if separated && !out.is_empty() {
                out.push('_');
            }
            separated = false;
            out.extend(character.to_lowercase());
        } else {
            separated = true;
        }
    }
    if out.is_empty() {
        return "module".to_string();
    }
    if out.starts_with(|character: char| character.is_ascii_digit()) {
        out.insert(0, '_');
    }
    out
}

/// `gg::views::open_file("src/main.cpp");`, or the same call with `{.offset = 400, .limit = 200}`
/// for a window — with the call itself already spelled by the language that asked.
///
/// Deliberately the plainest statement that does the job: no binding, no printing. It is synthesized
/// into the agent's own transcript and read by the model as an example of its own output, so
/// anything clever in it is a style the run did not intend to teach.
///
/// The window is a **designated initialiser** for the call's own optional argument, which is what
/// this SDK offers instead of keyword arguments and what a C++23 author writes. The whole-file form
/// passes nothing at all, because the argument has a default and a C++ author does not write `{}`
/// where the default is what they wanted.
///
/// The path is rendered through [`serde_json`] so a quote or a backslash in one cannot produce a
/// statement that would not parse: C++'s ordinary string literals accept exactly the escapes JSON's
/// do.
pub(super) fn open_file_statement(
    open_file: &str,
    path: &str,
    window: Option<FileWindow>,
) -> String {
    let path = serde_json::Value::String(path.to_string());
    match window {
        Some(window) => format!(
            "{open_file}({path}, {{.offset = {}, .limit = {}}});",
            window.offset, window.limit
        ),
        None => format!("{open_file}({path});"),
    }
}

/// A whole translation unit that opens one file view per entry of `views`: the module's own
/// `#include` line, an `int main`, and one call per view in the order given.
///
/// The seam's default is the statement list, and this arm cannot take it: a bare statement has
/// nowhere to live in C++ and [gg refuses](self::source::defines_main) a reply that defines no
/// `main`. So what gg pushes into the transcript is a program the model really could have sent —
/// which is the whole reason the seam lets a language answer this for itself.
///
/// Each call is written by [`open_file_statement`], indented by two, so the one place a file-view
/// call is spelled stays one place.
pub(super) fn open_file_program(
    includes: &str,
    open_file: &str,
    views: &[(&str, Option<FileWindow>)],
) -> String {
    let calls: String = views
        .iter()
        .map(|(path, window)| format!("  {}\n", open_file_statement(open_file, path, *window)))
        .collect();
    format!("{includes}int main() {{\n{calls}  return 0;\n}}\n")
}

/// A whole translation unit: an array of names and a range `for` over it, each iteration opening one
/// documentation view.
///
/// It is a **whole program** rather than a statement list, and this arm is the one where that is
/// forced by the grammar rather than chosen: C++ has nowhere for a statement to live except a
/// function body, and gg [refuses](self::source::defines_main) a reply that defines no `main`. So
/// what this generates is what it has to be, and what the seam asks for anyway — the on-use script
/// of every [built-in family skill](crate::skills) is a program.
///
/// An array and a loop rather than one call per name because the list is as long as the family —
/// eleven calls written out would be a program a model reads as a style to copy — and a
/// `std::array` deduced from its initialiser rather than a `std::vector`, because it is a fixed list
/// of string literals and allocating for one is what a C++ author would not do. The loop is a range
/// `for` over `const auto &`, which is the same author's default.
///
/// The empty case is spelled with an explicit element type and length, because an empty braced
/// initialiser gives `std::array` nothing to deduce from — *no viable constructor or deduction
/// guide* — and the `(void)` cast keeps a program that declares an array it never reads from being
/// a warning about one.
///
/// [`standard_includes`] is what declares that `std::array`, above the call's own include line: this
/// program obeys the rule a model's program obeys, and nothing is in scope of it that a line in it
/// did not put there.
pub(super) fn open_docs_views_statement(
    includes: &str,
    open_docs_view: &str,
    names: &[&str],
) -> String {
    let entries: Vec<String> = names
        .iter()
        .map(|name| format!("      {}", serde_json::Value::String((*name).to_string())))
        .collect();
    let listed = match entries.is_empty() {
        true => {
            "  const std::array<std::string_view, 0> functions{};\n  (void)functions;\n".to_string()
        }
        false => format!(
            "  const std::array functions{{\n{},\n  }};\n",
            entries.join(",\n")
        ),
    };
    format!(
        "{}{includes}int main() {{\n{listed}  for (const auto &name : functions) {{\n    \
         {open_docs_view}(name);\n  }}\n  return 0;\n}}\n",
        standard_includes(names.is_empty())
    )
}

/// The four calls the [opening program](bootstrap_program) writes, and the `#include` lines that
/// declare them.
///
/// One value rather than five parameters: this arm needs the include block as well as the spellings,
/// and five strings in a row is a call site whose arguments are told apart by counting.
pub(super) struct BootstrapCalls<'a> {
    /// The `#include` lines for exactly the modules this program calls into.
    pub includes: &'a str,
    /// This arm's spelling of the documentation search.
    pub search: &'a str,
    /// This arm's spelling of the documentation-view open.
    pub open_docs_view: &'a str,
    /// This arm's spelling of the workspace tree.
    pub tree_call: &'a str,
    /// This arm's spelling of the text-view open.
    pub open_text: &'a str,
}

/// The opening turn: one `int main` holding one search over every module gg listed and an array of
/// names opened as documentation views, with a range `for` over it.
///
/// A whole translation unit defining `main`, because this arm has nowhere else to put a statement
/// and [refuses](self::source::defines_main) a reply that defines none.
///
/// **One search rather than one per module**, because the filter is a union: the modules are a
/// braced list inside the filters, so the whole listing is read by a single call. A loop of a dozen
/// calls where one would do is a shape a model would copy for its own work — and so is a query of
/// `""` beside a filter that already says everything, which is why the search carries the modules
/// and the page and nothing else.
///
/// The array of keys, the `const auto &` loop, the empty case's explicit element type and the
/// [standard-library include lines](standard_includes) that declare them are what
/// [`open_docs_views_statement`] argues for, unchanged.
///
/// An agent that holds neither `files` nor `shell` is handed **no modules at all**, and a search
/// that names no module and asks no question is the one call this family refuses. That program is
/// written without the search — and without the `#include` that declared it — rather than opening
/// the session on gg's own `invalid-argument`.
///
/// It is the one program in this file that is compiled and run **before the model's first
/// request**, so a missing include here is a run that ends on gg's own defect rather than a turn a
/// model can act on.
///
/// The filters are an aggregate filled in with **designated initialisers**, which is what this
/// language offers in place of named arguments and what its SDK declares.
///
/// A failed call throws and nothing here catches it, which is this arm's failure model: a bootstrap
/// that caught its own failure would be a worked example of swallowing one.
pub(super) fn bootstrap_program(
    calls: BootstrapCalls<'_>,
    modules: &[&str],
    docs: &[&str],
    tree: Option<u32>,
) -> String {
    let BootstrapCalls {
        includes,
        search,
        open_docs_view,
        tree_call,
        open_text,
    } = calls;
    let walked = match tree {
        None => String::new(),
        Some(depth) => format!(
            "  {open_text}({}, {tree_call}({{.depth = {depth}}}));\n\n",
            serde_json::Value::String(WORKSPACE_TREE_VIEW.to_string())
        ),
    };
    let paths: Vec<String> = modules
        .iter()
        .map(|path| serde_json::Value::String((*path).to_string()).to_string())
        .collect();
    let lookup = match paths.is_empty() {
        true => String::new(),
        false => format!(
            "  {search}({{.modules = {{{}}}, .limit = {MAX_SEARCH_LIMIT}}});\n\n",
            paths.join(", ")
        ),
    };
    let entries: Vec<String> = docs
        .iter()
        .map(|name| format!("      {}", serde_json::Value::String((*name).to_string())))
        .collect();
    let functions = match entries.is_empty() {
        true => {
            "  const std::array<std::string_view, 0> functions{};\n  (void)functions;\n".to_string()
        }
        false => format!(
            "  const std::array functions{{\n{},\n  }};\n",
            entries.join(",\n")
        ),
    };
    format!(
        "{}{includes}int main() {{\n{walked}{lookup}{functions}  for (const auto &name : functions) \
         {{\n    {open_docs_view}(name);\n  }}\n  return 0;\n}}\n",
        standard_includes(docs.is_empty())
    )
}


/// This arm's catalogue, reflected out of the SDK's own doc comments by
/// `packages/gg-sandbox-purescript/signatures.sh` with `purs compile --codegen docs`.
///
/// It is not committed. `crates/gg/build.rs` runs that reflection as a step of building this
/// crate and this line embeds what it wrote into the build's own `OUT_DIR`, so what a model is
/// told about this arm is reflected out of the SDK sources in this checkout, on the build that
/// compiles the module telling it.
const SIGNATURES: &str = include_str!(concat!(
    env!("OUT_DIR"),
    "/signatures/purescript.signatures.json"
));

/// The parsed catalogue, parsed once per process.
static CATALOGUE: OnceLock<SignatureCatalogue> = OnceLock::new();

/// The one instance of this language. A unit struct, so the `static` costs nothing and coerces
/// straight to `&'static dyn ProgramLanguage`.
pub(super) static PURESCRIPT: PureScript = PureScript;

/// PureScript: compiled to JavaScript on the host by `purs`, bundled by `esbuild`, and evaluated as
/// a module by the shared ECMAScript guest.
pub(super) struct PureScript;

impl ProgramLanguage for PureScript {
    fn id(&self) -> GgProgramLanguage {
        GgProgramLanguage::PureScript
    }

    fn display_name(&self) -> &'static str {
        GgProgramLanguage::PureScript.display_name()
    }

    /// `CsvTools.parse` — a qualified name of the module's own alias, which is what the
    /// [import line](Self::lib_import) beside it bound.
    fn lib_access(&self, key: &str) -> String {
        format!("{}.{LIB_ACCESS_NAME}", alias(key))
    }

    /// `import Lib.CsvTools as CsvTools` — the line a program writes to reach a loaded module, and
    /// the same kind of line it writes to reach `Gg.Files`.
    ///
    /// A code module is [compiled into the program's own `purs` project](compile), under
    /// [`Lib.<Key>`](module_path()), so nothing about reaching it is this arm's invention: the program
    /// imports a module, aliases it, and calls a function `purs` type-checked against the author's
    /// signature.
    fn lib_import(&self, key: &str) -> Option<String> {
        Some(format!("import {} as {}", module_path(key), alias(key)))
    }

    /// The `purs` compile and the `esbuild` bundle, in this preparation's own hard-linked tree — see
    /// [`compile`] for what it costs, what it shares, and how it tells a program `purs` refused from
    /// a `purs` that could not run.
    fn prepare_program(
        &self,
        source: &str,
        modules: &[CodeModule],
        context: &PrepareContext,
    ) -> Result<PreparedProgram, PrepareFailure> {
        compile::compile_program(source, modules, context)
    }

    /// `purs`, which is what a PureScript programmer calls it and what its own binary is called — not
    /// `esbuild`, which flattens what it emitted and judges nothing about the program except that it
    /// has an entry point.
    ///
    /// Naming one is also what has the ~290 ms compile — paid on the failing path as much as the
    /// succeeding one — [recorded](crate::sandbox::SandboxOutcome::compile) rather than absorbed.
    fn checker(&self) -> Option<&'static str> {
        Some("purs")
    }

    /// Unpack the embedded library tree — 1.4 MB into 1,430 files, once per machine — so the first
    /// code turn is not charged for it.
    ///
    /// Idempotent and best effort: the result is cached for the process, and a failure here is
    /// dropped rather than reported, because the first compile makes the same attempt and fails there
    /// as a [toolchain failure](PrepareFailure::Toolchain) the run is told about properly.
    fn warm_prepare(&self) {
        compile::warm();
    }

    /// A `purs` compile of the author's module **on its own**, and the names it offers.
    ///
    /// What travels on is the author's source rather than anything compiled: a module is a module of
    /// the [program's own project](compile), written into it under the key the module was bound at,
    /// so the compile that matters is the one the program's own turn runs. This one exists to answer
    /// the use that loaded it — a module `purs` refuses is refused here, in the author's own
    /// coordinates, rather than by the next program that has it in scope.
    ///
    /// The guest is handed that source as well, and resolves none of it: the module's JavaScript is
    /// already inside the bundle of every program that imported it, so nothing in the guest ever
    /// asks for the module by name.
    ///
    /// What the module offers is read here rather than in the guest, because it is what the model is
    /// *told*: see [`modules`].
    fn prepare_module(
        &self,
        source: &str,
        context: &PrepareContext,
    ) -> Result<PreparedModule, PrepareFailure> {
        compile::check_module(source, context)?;
        Ok(PreparedModule {
            source: source.to_string(),
            exports: modules::exports(source),
        })
    }

    /// `.purs`, and nothing else.
    ///
    /// One extension, like [Python](super::python)'s and [Ruby](super::ruby)'s: nothing else in the
    /// registry can evaluate a PureScript module — this arm's guest could evaluate the *compiled*
    /// output, but a skills directory holds sources rather than artifacts — so a skill whose code is
    /// spelled `skill.rb` is a skill this arm's agents are not offered.
    fn module_file_extensions(&self) -> &'static [&'static str] {
        &["purs"]
    }

    /// [PascalCase](self::binding_name), which is what a PureScript module name is made of: the key
    /// is the last component of `Lib.<Key>` and the alias every call to the module carries.
    fn binding_name(&self, name: &str) -> String {
        binding_name(name)
    }

    /// The [ECMAScript guest](super::ecmascript), which the [TypeScript](super::typescript) and
    /// [JavaScript](super::javascript) arms are also registered against: one artifact, embedded
    /// once, evaluating every module gg compiles to JavaScript.
    fn guest_component(&self) -> Option<&'static [u8]> {
        Some(super::ecmascript::embedded())
    }

    /// This guest arms an interrupt handler off `GG_SANDBOX_DEADLINE_MS`, so a runaway loop is
    /// stopped by quickjs with `InternalError: interrupted` and the JavaScript frames rather than by
    /// gg's epoch trap. See [`stops_itself_at_ggs_deadline`](ProgramLanguage::stops_itself_at_ggs_deadline).
    fn stops_itself_at_ggs_deadline(&self) -> bool {
        true
    }

    /// The **composition** of `purs`'s source map and `esbuild`'s, which `esbuild` performs itself
    /// and inlines into the bundle it writes.
    ///
    /// A frame the engine reports as a position in the bundle therefore reads back as
    /// `program.purs:11:27` — the model's own file at the line it wrote — and a frame in a library
    /// or in this arm's SDK reads as that PureScript module's own path in the shipped tree. The name
    /// each frame takes is the one the map itself records for the token, rather than a single name
    /// gg picks, because a bundle is made of many sources and only the map knows which one a frame
    /// came from.
    ///
    /// Two sources in that map are neither the model's nor a library's, and their frames are struck
    /// rather than reported: [the entry module](compile::ENTRY_FILE) gg generates for the bundler,
    /// and any position in the bundle the composed map resolves nothing for.
    ///
    /// One map covers every frame, code modules included: a module is compiled into the program's
    /// own project, so its JavaScript is part of the one bundle and its `Lib.<Key>.purs` is one of
    /// the sources the composition resolves to.
    fn locations(&self, program: &str, _modules: &[CodeModule]) -> Option<Locations> {
        Locations::read(std::iter::once((
            super::ecmascript::PROGRAM.to_string(),
            None,
            program,
        )))
        .map(|locations| locations.hiding([compile::ENTRY_FILE.to_string()]))
    }

    /// This language's catalogue, parsed once and checked to be **this** language's.
    ///
    /// Every registered language's build reflects one of these under its own stem into the one
    /// `OUT_DIR`, and each carries the language it was generated for; checking it here is what stops
    /// a catalogue written — or embedded — under the wrong stem from reaching a model as a system
    /// prompt describing a sandbox nobody has.
    fn catalogue(&self) -> &'static SignatureCatalogue {
        CATALOGUE.get_or_init(|| {
            let catalogue = SignatureCatalogue::parse(SIGNATURES)
                .expect("the generated signature catalogue is valid JSON of the expected shape");
            assert_eq!(
                catalogue.language,
                GgProgramLanguage::PureScript,
                "`signatures/purescript.signatures.json` was generated for another program language",
            );
            catalogue
        })
    }

    fn healing(&self) -> &'static dyn crate::healing::Dialect {
        &healing::PURESCRIPT_DIALECT
    }

    /// [`void (Gg.Views.openFile "src/Main.purs" {})`](self::open_file_statement) — the call, its
    /// options record, and the `void` that discards what it hands back.
    fn open_file_statement(&self, path: &str, window: Option<FileWindow>) -> String {
        open_file_statement(&spell(self, VIEWS_OPEN_FILE), path, window)
    }

    /// [A module that imports the view module and folds a `for_` over an array of
    /// names](self::open_docs_views_statement), each iteration opening one documentation view.
    fn open_docs_views_statement(&self, names: &[&str]) -> String {
        open_docs_views_statement(&spell(self, VIEWS_OPEN_DOCS_VIEW), names)
    }

    /// [A module whose `main` folds a `for_` over each of two arrays](self::bootstrap_program), with
    /// both calls resolved from this language's own catalogue and both modules imported by name.
    fn bootstrap_program(&self, modules: &[&str], docs: &[&str]) -> String {
        bootstrap_program(
            &spell(self, DOCS_SEARCH),
            &spell(self, VIEWS_OPEN_DOCS_VIEW),
            modules,
            docs,
        )
    }
}


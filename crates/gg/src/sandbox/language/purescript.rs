/// `csv-tools` → `CsvTools`, `my_helpers.v2` → `MyHelpersV2`, `9lives` → `Module9lives`,
/// `CSV-tools` → `CSVTools`.
///
/// The key on this arm is a **proper name**, because [the module a program imports](module_path()) is
/// `Lib.<Key>` and a PureScript module name is a dotted sequence of proper names. So the key is
/// PascalCase: any separator — `-`, `_`, `.`, or anything a name should not have had — joins the
/// next word rather than surviving into an identifier that would not parse, and the front comes up.
/// A name with nothing usable in it, and one that would open with a digit, are prefixed `Module`,
/// which is the one word that leaves the result a name PureScript will read.
///
/// Deliberately ASCII-only, though PureScript identifiers may be Unicode: the key is what the model
/// types in the import line of every program that uses the module, and a name a model has to
/// reproduce exactly is one that should have no characters it could get wrong.
pub(super) fn binding_name(name: &str) -> String {
    let mut out = String::new();
    let mut capitalize = true;
    for ch in name.chars() {
        if ch.is_ascii_alphanumeric() {
            if capitalize {
                out.extend(ch.to_uppercase());
                capitalize = false;
            } else {
                out.push(ch);
            }
        } else {
            capitalize = true;
        }
    }
    match out.starts_with(|ch: char| ch.is_ascii_uppercase()) {
        true => out,
        false => format!("Module{out}"),
    }
}

/// The module one code module is compiled as, and the one a program imports: `Lib.CsvTools`.
///
/// `Lib` is gg's namespace rather than a package anything publishes, which is what keeps a key from
/// ever colliding with the shipped library set; a program that names one of these itself is
/// [refused](compile) with a sentence naming the key.
pub(super) fn module_path(key: &str) -> String {
    format!("Lib.{}", alias(key))
}

/// The alias a program binds that module under, and the qualifier every call to it carries.
///
/// The key itself, which [`binding_name`] already spells as a proper name. It is written through
/// this rather than used directly so that a key from anywhere else — the seam's own gates ask for
/// `lib_access("csvTools")` — still produces a line PureScript would parse.
fn alias(key: &str) -> String {
    let mut characters = key.chars();
    match characters.next() {
        None => "Module".to_string(),
        Some(first) => first.to_uppercase().collect::<String>() + characters.as_str(),
    }
}

/// `void (open_file "src/Main.purs" {})`, or
/// `void (open_file "src/Main.purs" { offset: 400, limit: 200 })` for a window — with `open_file`
/// already spelled by the language that asked.
///
/// Deliberately the plainest statement that does the job: no binding, no `where`, no logging. It is
/// synthesized into the agent's own transcript and read by the model as an example of its own output,
/// so anything clever in it is a style the run did not intend to teach.
///
/// Three things about it are this language's and are the reason this is a method rather than a
/// `format!` somewhere shared. The window is a **record**, which is this arm's idiom for optional
/// arguments and the shape the system prompt teaches — and the record is written even when there is
/// no window, because `{}` is how a PureScript program says "none of them" to a row-typed argument
/// rather than leaving it off. The call is wrapped in `void`, because a `do` block discards a
/// statement's value only when it is `Unit` and this one hands back a `FileRead`; a bare call would
/// be a `Discard` instance that does not exist. And there is no terminator, because PureScript does
/// not have one.
///
/// The path is rendered through [`serde_json`] so a quote or a backslash in one cannot produce a
/// statement that would not parse: PureScript's string literals accept exactly the escapes JSON's do.
///
/// What a caller does with several of these is join them with newlines, which composes them into the
/// **body** of a `do` block rather than into a whole module. That is the seam's shape rather than
/// this arm's choice — it hands a language one path at a time — and it is the right half to be given,
/// because the body is what a model writing its next program actually types.
pub(super) fn open_file_statement(
    open_file: &str,
    path: &str,
    window: Option<FileWindow>,
) -> String {
    let path = serde_json::Value::String(path.to_string());
    let options = match window {
        Some(window) => format!("{{ offset: {}, limit: {} }}", window.offset, window.limit),
        None => "{}".to_string(),
    };
    format!("void ({open_file} {path} {options})")
}

/// A module with an array of names and a `for_` over it, each iteration opening one documentation
/// view.
///
/// A whole module, because that is what a PureScript program is: this is the on-use script of every
/// built-in family skill, so it is handed straight to the prepare step and really is compiled.
///
/// A top-level array and a `for_` rather than a `let` inside the `do` block, because a top-level
/// declaration carries its own type signature — which is what makes the empty case
/// (`functions = []`, for an object with nothing enabled) a program rather than an ambiguous type.
/// The names are rendered through [`serde_json`] for the reason a path is: a name carrying a quote
/// would otherwise produce a program that does not parse. Leading commas, because that is how
/// PureScript writes a list.
pub(super) fn open_docs_views_statement(open_docs_view: &str, names: &[&str]) -> String {
    let mut entries = String::new();
    for (index, name) in names.iter().enumerate() {
        let separator = if index == 0 { '[' } else { ',' };
        let name = serde_json::Value::String((*name).to_string());
        entries.push_str(&format!("  {separator} {name}\n"));
    }
    if entries.is_empty() {
        entries.push_str("  [\n");
    }
    let module = module_of(open_docs_view);
    format!(
        "module Main where\n\
         \n\
         import Prelude\n\
         \n\
         import Data.Foldable (for_)\n\
         import Effect (Effect)\n\
         import {module} as {module}\n\
         \n\
         functions :: Array String\n\
         functions =\n\
         {entries}  ]\n\
         \n\
         main :: Effect Unit\n\
         main = for_ functions {open_docs_view}\n"
    )
}

/// The opening turn: a module whose `main` folds a `for_` over the module paths, listing each in
/// full, and then a `for_` over the names it opens documentation views of.
///
/// A whole module, because that is what a PureScript program is — and the two arrays are top-level
/// declarations carrying their own type signatures, for the reason
/// [`open_docs_views_statement`]'s one is: a `let` of an empty
/// array inside the `do` block would be an ambiguous type rather than a program.
///
/// Each module the program calls into is imported under its own full name, which is the name the
/// documentation is keyed by and the expression a program writes. The filters are the fields of a
/// **record** argument, which is this language's idiom for optional ones.
///
/// A failed call is thrown rather than returned, and nothing here catches it: that is this arm's
/// failure model, and a bootstrap that handled its own failure would be a worked example of
/// swallowing one.
pub(super) fn bootstrap_program(
    search: &str,
    open_docs_view: &str,
    modules: &[&str],
    docs: &[&str],
) -> String {
    let listed = |names: &[&str]| -> String {
        let mut entries = String::new();
        for (index, name) in names.iter().enumerate() {
            let separator = if index == 0 { '[' } else { ',' };
            let name = serde_json::Value::String((*name).to_string());
            entries.push_str(&format!("  {separator} {name}\n"));
        }
        if entries.is_empty() {
            entries.push_str("  [\n");
        }
        entries
    };
    let paths = listed(modules);
    let functions = listed(docs);
    // Two calls, and on this arm each needs its own import line — unless the SDK ever files both
    // under one module, in which case importing it twice would be the compile error rather than the
    // program.
    let docs_module = module_of(search);
    let views_module = module_of(open_docs_view);
    let mut imports = format!("import {docs_module} as {docs_module}\n");
    if views_module != docs_module {
        imports.push_str(&format!("import {views_module} as {views_module}\n"));
    }
    format!(
        "module Main where\n\
         \n\
         import Prelude\n\
         \n\
         import Data.Foldable (for_)\n\
         import Effect (Effect)\n\
         {imports}\
         \n\
         modules :: Array String\n\
         modules =\n\
         {paths}  ]\n\
         \n\
         functions :: Array String\n\
         functions =\n\
         {functions}  ]\n\
         \n\
         main :: Effect Unit\n\
         main = do\n\
         \x20 for_ modules \\path -> {search} \"\" {{ module: path, limit: {MAX_SEARCH_LIMIT} }}\n\
         \x20 for_ functions {open_docs_view}\n"
    )
}

/// The module a fully-qualified call is documented under, taken off the front of the call itself.
///
/// The one place gg has to write this arm's **import** line, and it is derived from the call rather
/// than looked up beside it so that the two cannot disagree: an import of some other module would
/// leave the call it was written for unresolved, which is a program that does not compile in the one
/// place a model reads gg's own output as an example of its own. Every catalogued name is
/// module-qualified — the name rule (`signatures.fqn.rs`) is what makes that true on
/// every arm — so the module is everything before the last separator, and a call that somehow
/// carried none is imported as itself rather than crashing a turn.
fn module_of(call: &str) -> &str {
    call.rsplit_once('.').map_or(call, |(module, _)| module)
}


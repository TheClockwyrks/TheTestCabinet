//! **PureScript** — gg's fifth registered [program language](super::ProgramLanguage), and the first
//! whose compiler is a **binary in the run image** rather than something gg carries inside its own
//! executable.
//!
//! Everything this arm owns lives here or in one of this module's siblings:
//!
//! * [`compile`] — the host-side `purs` and `esbuild` compile that turns a model's PureScript into
//!   the JavaScript the guest evaluates, what it costs, what it shares, and the two failures it
//!   tells apart;
//! * [`modules`] — reading a code [skill](crate::skills)'s or [memory](crate::memories)'s own
//!   module header for the names it offers and the types each of them writes;
//! * [`healing`] — the [dialect](crate::healing::Dialect) response healing asks its lexical
//!   questions of: the fence tags, the two predicates, and the nesting-and-primes lexer;
//! * `packages/gg-sandbox-purescript/src/Gg/**` — the hand-written SDK, compiled **into** the library
//!   tree below, so the surface a model is shown and the surface its program is compiled against are
//!   one artifact;
//! * the **signature catalogue** — reflected out of that SDK by `purs compile --codegen docs`, and
//!   generated into this build's `OUT_DIR` rather than committed anywhere (see
//!   `crates/gg/build.rs`);
//! * `purescript.libraries.tar.gz` and `purescript.compiler.json` — the compiled library set and
//!   the manifest of what is in it, generated by `crates/gg-sandbox-artifacts/purescript` into this
//!   build's own `OUT_DIR` rather than committed anywhere, and reached through
//!   `GG_ARTIFACTS_PURESCRIPT`. That tarball is also what the catalogue above is reflected against,
//!   which is why this is the one arm whose artifact crate is an ORDERING constraint as well as a
//!   source of bytes.
//!
//! # The strategy, in one sentence
//!
//! **A PureScript program is compiled to JavaScript on the host by `purs`, flattened into one ES
//! module by `esbuild`, and evaluated as a module by the [ECMAScript guest](super::ecmascript).**
//!
//! Nothing about it is per-run: the tree a program is compiled against is a build-time artifact, the
//! compiler is a binary in the gg toolchain image, and what crosses the membrane is JavaScript.
//!
//! # What a PureScript program is, here
//!
//! A **module**. PureScript has no loose statements, so a program is a module with its own header,
//! its own `main :: Effect Unit`, and an `import` line for each of gg's capability modules it uses
//! and each code module it has loaded. Every one of those is the model's: `purs` reads the reply and
//! nothing else, `purs` files the emitted JavaScript under the header the model wrote, and gg's
//! entry module imports `main` from there. A reply with no header is `ErrorParsingModule` at line 1
//! and a program that defines no `main` is refused with a sentence saying so, both before anything
//! runs.
//!
//! The bytes that **execute** are `purs`'s emission rather than the model's, which is the position
//! every compiled arm is in. What makes it legitimate is the pair the invariants require: the bytes
//! gg compiles are the model's, and a run-time location is recovered through the compilers' own
//! source maps — see [`locations`](crate::sandbox::ProgramLanguage::locations).
//!
//! The library set a program may import is a **build-time fact about the embedded tree** rather than
//! a policy: `packages/gg-sandbox-purescript/spago.yaml` declares it, the build compiles exactly that
//! set and everything it depends on, and the manifest records what shipped. It is deliberately
//! generous — the collections, the monad transformers and the profunctor lenses a PureScript author
//! reaches for without asking — because an arm that made a model live without its own idioms would be
//! measuring the wrong thing. **The SDK is compiled into that same tree**, which is why the tree
//! rides inside gg's binary rather than in the run image: a tree of one vintage and a binary of
//! another would mean a model shown one surface in its prompt and compiled against a different one.
//!
//! # What the SDK looks like, and why
//!
//! It is **idiomatic PureScript** rather than the TypeScript SDK transliterated, and every difference
//! is a spelling the seam leaves free:
//!
//! * **The surface is eleven capability modules** — `Gg.Files`, `Gg.Shell`, `Gg.Board`, … — plus a
//!   twelfth, `Gg.Core`, that binds no operation and holds the failure types every other module's
//!   signatures name. Each is a real PureScript module with an explicit export list, which is the
//!   best public-surface protocol of the eleven arms: `purs` will not let anything else escape.
//! * **A program writes the module's own name.** It is the one arm with a real import line, and the
//!   line aliases a module to itself: `import Gg.Files as Gg.Files` makes `Gg.Files.readFile` — the
//!   key a documentation view is opened by — the expression a call site writes, so the name a model
//!   reads and the name it types are one string. Verified against `purs`: an *open* import does not
//!   make a fully-qualified reference resolve, and a dotted alias does.
//! * **Free functions over values, and no member functions at all.** Where an arm with objects hangs
//!   `wait` off a handle, this one offers `Gg.Delegation.waitForSubagents` over it. A member on a
//!   record would be a field access no search can reach, which is the same failure an API object was.
//! * **Optional arguments are a record, and the row is checked.** `Union given rest ReadOptions` is
//!   PureScript's own idiom for "these fields, any subset of them": `Gg.Files.readFile "a" {}` and
//!   `Gg.Files.readFile "a" { limit: 20 }` both type-check, and `{ limitt: 20 }` is a type error
//!   naming every field that would have worked.
//! * **A three-way patch field needs no sentinel.** Leave `description` out of the record to keep it,
//!   pass `Nothing` to clear it, pass `Just` to replace it — where Python needs an `UNCHANGED`
//!   because `None` is already taken.
//! * **A fixed choice is a `data` type** (`TaskDone`, `IssueOpen`, `FileEntry`), and a read is a real
//!   sum type a program matches on rather than a `kind` field it compares against a string.
//! * **A failure is thrown and caught with `attempt`**, which is how effectful PureScript expresses a
//!   failure that is usually fatal to what you were doing; `Effect (Either ApiError a)` on every
//!   call would force a branch after every line.
//! * **The brief a child agent is spawned with is a constructor** — `Prompt` or `Issue` — so "both"
//!   and "neither" are programs that do not compile rather than calls the host refuses.
//!
//! The bridge underneath it is `Gg.Internal.Wire`, one foreign module whose JavaScript half writes
//! `import * as gg from "gg"` — the same line a TypeScript program writes, reaching the same SDK
//! instance in the same guest, so both arms produce byte-identical arguments for one capability. A
//! capability this run withheld is refused by the host as an `ApiError` carrying `unavailable`, as
//! it is on every arm. gg's own spellings for the families are the lowering and not the surface:
//! they are written once, beside the function that uses them, and a model never sees one.
//!
//! # What this arm has that no other does
//!
//! It is the only arm whose program is read by a **type system** and is not
//! [TypeScript](super::typescript)'s. That makes it the third point on the axis a study reads to
//! separate *checked* from *typed*: Python is unchecked and interpreted, JavaScript is unchecked and
//! lowered, Ruby is compiled without being typed, TypeScript is type-checked in a gradual system over
//! a dynamic language, and this arm is type-checked in a total one — where a call written with the
//! wrong argument shape, a `case` that misses an arm, or a missing instance is a diagnostic rather
//! than a turn.


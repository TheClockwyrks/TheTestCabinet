/// One language's probe fixture, as `crates/backend/src/probe/fixtures/<language>.json` carries it.
#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub(crate) struct ProbeFixture {
    /// Where these bytes came from and how to regenerate them.
    provenance: String,
    /// The [wire id](GgProgramLanguage::id) of the arm the fixture is spelled in.
    language: &'static str,
    /// The arm's display name, for the console.
    display_name: &'static str,
    /// The one `submit_program` tool the request offers, exactly as gg's own completion module
    /// builds it for this arm.
    tool: ProbeFixtureTool,
    /// One case per (scenario, prompt) pair.
    cases: Vec<ProbeFixtureCase>,
}

/// The `submit_program` tool definition in the chat/completions `function` shape.
#[derive(Debug, Serialize)]
struct ProbeFixtureTool {
    name: String,
    description: String,
    parameters: serde_json::Value,
}

/// One case: its identity, its full message array, and what the submitted program is checked for.
#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
struct ProbeFixtureCase {
    scenario: &'static str,
    prompt: &'static str,
    /// Call spellings ([`spell`]) a passing baseline program must all contain.
    #[serde(skip_serializing_if = "Vec::is_empty")]
    expected_calls: Vec<String>,
    /// The target call's spelling a passing missing-docview program must *not* contain.
    #[serde(skip_serializing_if = "Vec::is_empty")]
    forbidden_calls: Vec<String>,
    /// The documentation-view-opening call's spelling, for the missing-docview check.
    #[serde(skip_serializing_if = "Option::is_none")]
    docview_call: Option<String>,
    /// The catalogue key the missing function's documentation view is opened under.
    #[serde(skip_serializing_if = "Option::is_none")]
    docview_key: Option<String>,
    messages: Vec<ProbeFixtureMessage>,
}

/// One message of a case's conversation. `source` records which gg mechanism produced it and is
/// never sent on the wire.
#[derive(Debug, Serialize)]
struct ProbeFixtureMessage {
    role: &'static str,
    source: &'static str,
    #[serde(skip_serializing_if = "Option::is_none")]
    content: Option<String>,
    #[serde(skip_serializing_if = "Vec::is_empty")]
    tool_calls: Vec<ProbeFixtureToolCall>,
    #[serde(skip_serializing_if = "Option::is_none")]
    tool_call_id: Option<String>,
}

/// One synthesized `submit_program` call, in the chat/completions wire shape.
#[derive(Debug, Serialize)]
struct ProbeFixtureToolCall {
    id: &'static str,
    #[serde(rename = "type")]
    kind: &'static str,
    function: ProbeFixtureToolFunction,
}

/// The function half of a synthesized call.
#[derive(Debug, Serialize)]
struct ProbeFixtureToolFunction {
    name: &'static str,
    arguments: String,
}

impl ProbeFixtureMessage {
    /// A synthesized `submit_program` assistant turn carrying `program` under `id`.
    fn submission(id: &'static str, program: &str) -> Self {
        Self {
            role: "assistant",
            source: "assistant",
            content: None,
            tool_calls: vec![ProbeFixtureToolCall {
                id,
                kind: "function",
                function: ProbeFixtureToolFunction {
                    name: crate::completion::SUBMIT_PROGRAM_TOOL,
                    arguments: json!({ "program": program }).to_string(),
                },
            }],
            tool_call_id: None,
        }
    }

    /// The fixed `ok` acknowledgement answering the call `id`.
    fn acknowledgement(id: &'static str) -> Self {
        Self {
            role: "tool",
            source: "tool_result",
            content: Some(SUBMIT_PROGRAM_ACK.to_string()),
            tool_calls: Vec::new(),
            tool_call_id: Some(id.to_string()),
        }
    }

    /// A synthesized `user` view message: the heading, the `----` rule, and the body — the exact
    /// framing [`ContextModel::headed`](crate::context::ContextModel) sends.
    fn view(role_source: (&'static str, &'static str), heading: &str, body: &str) -> Self {
        Self {
            role: role_source.0,
            source: role_source.1,
            content: Some(format!("{heading}\n----\n{body}")),
            tool_calls: Vec::new(),
            tool_call_id: None,
        }
    }
}


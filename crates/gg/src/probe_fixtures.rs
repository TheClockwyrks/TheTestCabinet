/// Write one fixture per registered language into `directory`, creating it if it is not there.
///
/// Pretty-printed, unlike the reference's compact documents, because these are **committed** files:
/// a regeneration is reviewed as a diff, and a one-line JSON blob diffs as a whole-file rewrite.
pub(crate) fn write_probe_fixtures(directory: &Path) -> Result<(), ProbeFixtureWriteError> {
    std::fs::create_dir_all(directory).map_err(|source| ProbeFixtureWriteError {
        path: directory.to_path_buf(),
        detail: source.to_string(),
    })?;
    for id in GgProgramLanguage::ALL {
        let fixture = fixture_for(*id).map_err(|detail| ProbeFixtureWriteError {
            path: directory.join(format!("{}.json", id.id())),
            detail,
        })?;
        let path = directory.join(format!("{}.json", id.id()));
        let json =
            serde_json::to_string_pretty(&fixture).map_err(|err| ProbeFixtureWriteError {
                path: path.clone(),
                detail: err.to_string(),
            })?;
        std::fs::write(&path, json + "\n").map_err(|source| ProbeFixtureWriteError {
            path,
            detail: source.to_string(),
        })?;
    }
    Ok(())
}

/// A failure while projecting the fixtures, carrying the path it was attempting.
#[derive(Debug, thiserror::Error)]
#[error("{path}: {detail}")]
pub(crate) struct ProbeFixtureWriteError {
    /// The file or directory the failed step was operating on.
    path: PathBuf,
    /// What went wrong.
    detail: String,
}


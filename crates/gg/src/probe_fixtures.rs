/// Build one language's whole fixture, or the sentence naming the gg defect that stopped it.
pub(crate) fn fixture_for(id: GgProgramLanguage) -> Result<ProbeFixture, String> {
    let arm = language(id);
    let capabilities: Vec<String> = PROBE_CAPABILITIES.iter().map(|c| c.to_string()).collect();
    let operations = capability_operations(PROBE_CAPABILITIES.iter().copied());
    let role = EndingRole::Standard;
    let docs = DocsRuntime::new(capabilities.clone(), role, &operations, id);

    // The system prompt, rendered by the loop's own renderer over the same context shape the loop
    // builds: code mode, this arm's language view, the modules the grant reaches, the base code
    // headings (files on — the conversation seeds a file view), an uncapped text-only read, and a
    // standard worker's ending calls.
    let system = prompts::render_system(
        &SystemContext {
            responses_as_code: true,
            language: Some(prompts::language_view(id)),
            modules: module_views(&capabilities, &operations, role, id),
            code_headings: code_heading_views(false, false, true),
            read_file: ReadFileView {
                offered: true,
                line_cap: None,
                images: false,
            },
            ending: ending_view(role, Some(id)),
            ..SystemContext::default()
        },
        None,
    )?;

    // The modules the opening listing covers and the base documentation keys: the opening turn a
    // fresh profile is seeded with, resolved exactly as the bootstrap resolves an agent's own for a
    // real session — so an entry the probe agent does not hold (the workspace search, which its
    // grant does not buy) is dropped here exactly as a run would drop it.
    let resolved = resolve_opening_turn(
        &docs,
        &GgOpeningTurn::seeded(),
        &capabilities,
        &operations,
        role,
    );
    let modules = resolved.modules;
    let base_keys = resolved.keys;

    let tool = submit_program_tool(id);

    let cases = CASES
        .iter()
        .map(|case| build_case(id, &docs, &modules, &base_keys, &system, case))
        .collect::<Result<Vec<_>, String>>()?;

    Ok(ProbeFixture {
        provenance: format!(
            "gg's responses-as-code turn-1 request for the {} arm, projected by `gg \
             probe-fixtures` (regenerate with scripts/gg-probe-fixtures.sh). Nothing model-facing \
             is authored here twice: the system prompt, the opening bootstrap program, the module \
             listing, every documentation view and the file-view headings are the same bytes \
             gg's own machinery produces for a real session; the task \
             prompts and spec files are the probe's own material. The backend replays each case \
             through OpenRouter with the one `submit_program` tool offered and `tool_choice` \
             forced to it, and classifies the program each reply submitted.",
            arm.display_name()
        ),
        language: id.id(),
        display_name: arm.display_name(),
        tool: ProbeFixtureTool {
            name: tool.name,
            description: tool.description,
            parameters: tool.parameters,
        },
        cases,
    })
}

/// A call-site needle for one spelling: its last two segments, joined by the separator between
/// them. [`spell`] answers fully qualified (`gg.files.writeFile`, `gg::files::write_file`), while a
/// call site may drop the qualifier the arm's own rules drop (TypeScript writes `files.writeFile`,
/// Rust may `use gg::files;` and write `files::write_file`). Every correct form ends with these two
/// segments, so the suffix matches both the qualified and the shortened call.
fn call_needle(spelling: &str) -> String {
    let mut boundaries: Vec<usize> = Vec::new();
    let bytes = spelling.as_bytes();
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b':' && i + 1 < bytes.len() && bytes[i + 1] == b':' {
            boundaries.push(i);
            i += 2;
        } else if bytes[i] == b'.' {
            boundaries.push(i);
            i += 1;
        } else {
            i += 1;
        }
    }
    match boundaries.len() {
        0 | 1 => spelling.to_string(),
        n => {
            let start = boundaries[n - 2];
            let after = if bytes[start] == b':' {
                start + 2
            } else {
                start + 1
            };
            spelling[after..].to_string()
        }
    }
}

/// Build one case's message array and expectations.
fn build_case(
    id: GgProgramLanguage,
    docs: &DocsRuntime,
    modules: &[String],
    base_keys: &[String],
    system: &str,
    case: &CaseSpec,
) -> Result<ProbeFixtureCase, String> {
    let arm = language(id);
    let functions = catalogue_functions(arm);

    // The catalogue key of each operation the case names, in this arm's own spelling.
    let fqn_of = |operation: OperationId| -> Result<String, String> {
        bootstrap_function(&functions, operation, |function| docs.bound(function))
            .map(|function| function.fqn.to_string())
            .ok_or_else(|| {
                format!(
                    "the {} catalogue binds no `{operation}` for the probe agent's grant",
                    arm.display_name()
                )
            })
    };

    // The opening program: the bootstrap's module listing plus the base documentation views, with a
    // baseline case's target views appended to the same open list.
    let mut keys: Vec<String> = base_keys.to_vec();
    for operation in case.docs {
        let fqn = fqn_of(*operation)?;
        if !keys.contains(&fqn) {
            keys.push(fqn);
        }
    }
    let program = arm.bootstrap_program(
        &modules.iter().map(String::as_str).collect::<Vec<_>>(),
        &keys.iter().map(String::as_str).collect::<Vec<_>>(),
    );

    // The module listing, rendered by the loop's own renderer over the same search the bootstrap
    // program makes, keyed by the modules it lists.
    let query = DocSearchQuery {
        query: String::new(),
        modules: modules.to_vec(),
        declared_type: None,
        kind: None,
        offset: None,
        limit: Some(MAX_SEARCH_LIMIT),
    };
    let page = docs
        .search(DocQuery {
            query: &query.query,
            modules: &query.modules,
            declared_type: None,
            kind: None,
            offset: None,
            limit: query.limit,
        })
        .map_err(|refusal| {
            format!(
                "the bootstrap module listing was refused: {}",
                refusal.message
            )
        })?;
    let listing = crate::agent::code::render_search_results(&query, &page);
    let listing_heading = item_heading(
        GgContextSource::SearchResults,
        Some(&modules.join(", ")),
        None,
    )
    .ok_or_else(|| "a search view renders no heading".to_string())?;

    let mut messages = vec![
        ProbeFixtureMessage {
            role: "system",
            source: "system",
            content: Some(system.to_string()),
            tool_calls: Vec::new(),
            tool_call_id: None,
        },
        ProbeFixtureMessage::view(("user", "user_prompt"), "Task", case.task),
        ProbeFixtureMessage::submission(BOOTSTRAP_CALL_ID, &program),
        ProbeFixtureMessage::acknowledgement(BOOTSTRAP_CALL_ID),
        ProbeFixtureMessage::view(("user", "search_results"), &listing_heading, &listing),
    ];

    // The documentation views the opening program placed: each key's own page, then the type views
    // this agent's flags (every one on) select, deduplicated session-wide — the loop's own
    // one-call-one-level algorithm.
    let mut opened: Vec<String> = Vec::new();
    for key in &keys {
        for view_key in
            std::iter::once(key.clone()).chain(docs.types_to_open(key, DocViewTypes::EVERY))
        {
            if opened.contains(&view_key) {
                continue;
            }
            let body = docs.read_any(&view_key).ok_or_else(|| {
                format!(
                    "the {} documentation renders nothing under `{view_key}`",
                    arm.display_name()
                )
            })?;
            let heading = item_heading(GgContextSource::DocsView, Some(&view_key), None)
                .ok_or_else(|| "a documentation view renders no heading".to_string())?;
            messages.push(ProbeFixtureMessage::view(
                ("user", "docs_view"),
                &heading,
                &body,
            ));
            opened.push(view_key);
        }
    }

    // The spec file, seeded exactly as autoload seeds one: a synthesized program opening the view,
    // the acknowledgement, then the file view headed by its path, the whole 1-based line range and
    // the file's total line count.
    let files_program = arm.open_file_program(&[(case.spec_path, None)]);
    messages.push(ProbeFixtureMessage::submission(
        AUTOLOAD_CALL_ID,
        &files_program,
    ));
    messages.push(ProbeFixtureMessage::acknowledgement(AUTOLOAD_CALL_ID));
    let spec_text = case.spec_text.trim_end_matches('\n');
    let total = spec_text.lines().count() as u64;
    let heading = item_heading(
        GgContextSource::FileView,
        Some(case.spec_path),
        Some(ShownLines {
            first: 1,
            last: total,
            total,
        }),
    )
    .ok_or_else(|| "a file view renders no heading".to_string())?;
    messages.push(ProbeFixtureMessage::view(
        ("user", "file_view"),
        &heading,
        spec_text,
    ));

    Ok(ProbeFixtureCase {
        scenario: case.scenario,
        prompt: case.prompt,
        expected_calls: case
            .required
            .iter()
            .map(|operation| call_needle(&spell(arm, *operation)))
            .collect(),
        forbidden_calls: case
            .target
            .map(|operation| vec![call_needle(&spell(arm, operation))])
            .unwrap_or_default(),
        docview_call: case
            .target
            .map(|_| call_needle(&spell(arm, VIEWS_OPEN_DOCS_VIEW))),
        docview_key: case.target.map(fqn_of).transpose()?,
        messages,
    })
}


//! **The model-probe fixtures**: per-language turn-1 conversations the backend replays to check a
//! model's responses-as-code readiness, projected out of gg's own machinery.
//!
//! # Projected, never written
//!
//! This is the reference's rule ([`crate::reference`]) applied to the probe: not a word of the
//! model-facing content here is authored a second time. The system prompt is
//! [`prompts::render_system`] over the same context the loop builds, the opening turn's program is
//! the arm's own [`bootstrap_program`](crate::sandbox::ProgramLanguage::bootstrap_program), the
//! module listing is [`render_search_results`](crate::agent::code::render_search_results), every
//! documentation view is the string [`DocsRuntime::read_any`] renders, a file view's heading is
//! [`item_heading`] with its [`ShownLines`]. What this module *does* author is the probe's own
//! material:
//! the task prompts and the small spec files each task reads.
//!
//! # The two scenarios, and at least three prompts
//!
//! Each language's fixture carries one case per (scenario, prompt) pair:
//!
//! - **`baseline`** — the conversation holds an open documentation view of every function the task
//!   needs, and a ready model writes a program calling them. Two prompts: `write-plan`
//!   (`files.write_file`) and `inventory` (`files.list_dir` + `files.write_file`).
//! - **`missing-docview`** — the task needs a function whose documentation view is *not* open, and
//!   the system prompt instructs: "Open a documentation view of each function you intend to call,
//!   and write the call on a later turn." A ready model opens the view and stops; calling the
//!   undocumented function in the same program fails the case. Two prompts: `run-tests`
//!   (`shell.shell`) and `fix-typo` (`files.edit_file`).
//!
//! # Why the fixtures are committed files in the backend crate
//!
//! The backend must not link this crate (see `scripts/gg-reference.sh` for the whole argument), and
//! unlike the reference — served at run time from files an image bakes — the probe embeds its
//! request at compile time, so the projection crosses the crate boundary as **committed** JSON under
//! `crates/backend/src/probe/fixtures/`, regenerated by `scripts/gg-probe-fixtures.sh` whenever the
//! prompt, the catalogue or a case changes. Each file records that provenance inside itself.
//!
//! # The probe agent
//!
//! One fixed grant for every case: responses-as-code plus `shell`, `read-file`, `write-file`,
//! `edit-file` and `list-dir` — the surface a small build task actually reaches for — dispatched as
//! a standard worker with every documentation-view type flag on. The bootstrap's opening program
//! lists the `files` and `shell` modules and opens the base documentation views exactly as a real
//! session's does; a baseline case's target views are appended to that same program's open list.


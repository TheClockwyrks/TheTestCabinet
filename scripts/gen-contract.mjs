// Generate the Test Cabinet data contract — the TypeScript bindings and the JSON
// Schemas — from the Rust types that are its single source of truth.
//
// The work happens in four steps. First gg projects its own model-facing surface
// into `crates/backend/src/gg_reference.json`, because the backend serves that
// artifact and cannot reach the crate that produces it. Then the `contract-codegen`
// crate (see `crates/contract-codegen`) emits the TypeScript
// (`packages/run-record/src/`) and the JSON Schemas (`apps/docs/public/schema/`)
// from the Rust contract types, which derive `ts_rs::TS` + `schemars::JsonSchema`
// behind their `contract` feature. The Rust generator is correct but not pretty
// (ts_rs emits ragged whitespace), so the third step runs Prettier to make the
// committed output deterministic and conventional. CI regenerates and fails on any
// diff, so the committed artifacts always match the Rust source — hand-edits never
// survive. The last step compiles the regenerated TypeScript, because `dist/` — not
// `src/` — is what every consumer of the package actually imports.
//
// Usage: `npm run gen:contract` (from the repository root).

import { execFileSync } from "node:child_process";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

function run(cmd, args) {
  execFileSync(cmd, args, { stdio: "inherit" });
}

// 1. Project gg's reference — every tool's real description and parameter schema,
//    and every responses-as-code function's signature, doc and referenced types —
//    out of gg's own definitions, so the console's gg Reference section shows what
//    models are actually shown rather than a paraphrase that drifts.
//
//    It crosses the crate boundary as a committed artifact because the backend that
//    serves it (`GET /gg/reference`) must not depend on `test-cabinet-gg`: that crate
//    pulls wasmtime, oxc and tiktoken-rs, and the backend is built portable and static
//    under musl. So the artifact stands in for the dependency, and CI's
//    regenerate-and-diff check (`scripts/ci/contract-drift.sh`) is what makes it as
//    trustworthy as one. That is a shape gg's own program-language signature catalogues
//    deliberately do *not* use any more: they are read by the crate that generates them,
//    so they are simply generated by its build (`crates/gg/build.rs`) and never
//    committed. Committing is what you do when the reader cannot run the generator, and
//    the backend genuinely cannot.
//
//    Which means this line BUILDS gg, and building gg reflects all eleven of those
//    catalogues out of their guest SDKs. Whoever runs `npm run gen:contract` needs gg's
//    program-language toolchains installed — `scripts/ci/install-gg-toolchains.sh` — or
//    the build stops with a sentence naming what is missing.
//
//    This runs *first*, before the codegen below, and that order is load-bearing:
//    the backend `include_str!`s the file, and `contract-codegen` links the backend,
//    so the artifact has to be on disk before step 2 can build at all. Generating it
//    last would mean a deleted file could never be regenerated.
{
  const reference = execFileSync(
    "cargo",
    [
      "run",
      "--quiet",
      "-p",
      "test-cabinet-gg",
      "--bin",
      "gg",
      "--",
      "reference",
    ],
    {
      encoding: "utf8",
      // Cargo's build progress goes to stderr and should stay visible; only the
      // JSON on stdout is captured.
      stdio: ["ignore", "pipe", "inherit"],
      // The reference is ~100 KB today and grows with every tool gg gains, which
      // would silently blow Node's 1 MiB default and fail the build for a reason
      // that reads like a cargo error.
      maxBuffer: 64 * 1024 * 1024,
    },
  );
  // Exactly one trailing newline; Prettier below re-indents the body, so this only
  // has to be valid JSON.
  writeFileSync(
    "crates/backend/src/gg_reference.json",
    `${reference.trimEnd()}\n`,
  );
}

// 2. Emit raw TS + JSON from the Rust source of truth.
run("cargo", ["run", "--quiet", "-p", "contract-codegen"]);

// 2b. Mirror gg's built-in system-prompt templates into the TS contract, so the
//     console can seed its per-agent "System Prompt" editor with the exact default
//     an agent's `systemPromptTemplate` override starts from. There are two, chosen
//     by the agent's execution mode: the tool-calling arm names each capability's
//     free-standing tools, and the responses-as-code arm names their grouped methods
//     and teaches the code protocol. The code arm is per **program language** — its
//     file is `system-code.<language id>.hbs` — so *every* one is mirrored, keyed by
//     language id, plus the default language's under its own name for the reader who
//     just wants "the code prompt".
//     The `.hbs` files are the single source of truth (they are what the gg binary
//     renders); this keeps the TS copy from drifting, and CI's regenerate-and-diff
//     check enforces it.
{
  const tools = readFileSync("crates/gg/templates/system-tools.hbs", "utf8");
  // Every registered program language's code template, keyed by the language id its filename
  // carries. Discovered from the directory rather than listed here, so a language whose template
  // landed in the tree is mirrored without anyone editing this script — the "additive" property the
  // seam exists for has to hold on this side of the wire too.
  const codeTemplates = Object.fromEntries(
    readdirSync("crates/gg/templates")
      .filter(
        (file) => file.startsWith("system-code.") && file.endsWith(".hbs"),
      )
      .sort()
      .map((file) => [
        file.slice("system-code.".length, -".hbs".length),
        readFileSync(`crates/gg/templates/${file}`, "utf8"),
      ]),
  );
  const defaultLanguage = "typescript";
  const code = codeTemplates[defaultLanguage];
  if (!code) {
    throw new Error(
      `no system-code.${defaultLanguage}.hbs — gg's default program language has no template`,
    );
  }
  writeFileSync(
    "packages/run-record/src/gg-system-prompt.ts",
    "// AUTO-GENERATED by scripts/gen-contract.mjs from crates/gg/templates/system-tools.hbs\n" +
      "// and every crates/gg/templates/system-code.<language>.hbs.\n" +
      "// DO NOT EDIT BY HAND — edit the .hbs templates and run `npm run gen:contract`.\n\n" +
      "/**\n" +
      " * gg's built-in **tool-calling** system-prompt Handlebars template, verbatim — the\n" +
      " * default a tool-calling agent's `systemPromptTemplate` override starts from, and what\n" +
      " * the console seeds its per-agent System Prompt editor with for one. Partials are\n" +
      " * inlined, so it is self-contained; variables/branches are left intact.\n" +
      " */\n" +
      `export const DEFAULT_GG_SYSTEM_PROMPT_TEMPLATE = ${JSON.stringify(tools)};\n\n` +
      "/**\n" +
      " * gg's built-in **responses-as-code** system-prompt Handlebars template for every\n" +
      " * registered program language, keyed by language id.\n" +
      " *\n" +
      " * The code arm is per language — the prompt quotes the SDK throughout, and a function's\n" +
      " * spelling is precisely what differs between two languages — so an editor seeding the\n" +
      " * default for a code-mode agent has to seed *that agent's* language's template. Seeding\n" +
      " * one language's prompt onto another's agent would persist an override written in the\n" +
      " * wrong syntax the moment an operator edited a line of it.\n" +
      " */\n" +
      `export const DEFAULT_GG_SYSTEM_PROMPT_TEMPLATES_CODE: Readonly<Record<string, string>> = ${JSON.stringify(codeTemplates)};\n\n` +
      "/**\n" +
      " * gg's **default** program language's responses-as-code template — the arm an agent that\n" +
      ' * configures no language is held to, and the one a reader wanting "the code prompt"\n' +
      " * means. Self-contained, like its tool-calling sibling.\n" +
      " */\n" +
      `export const DEFAULT_GG_SYSTEM_PROMPT_TEMPLATE_CODE = ${JSON.stringify(code)};\n`,
  );
}

// 3. Normalize formatting so the committed artifacts are deterministic. Prettier
//    is pinned (see the root `package.json`) so the same input always formats the
//    same way, which is what makes the drift check trustworthy. gg's reference is
//    formatted here too rather than trusted to `serde_json`'s pretty printer: the
//    drift check diffs the committed bytes, so every artifact it guards has to come
//    out of the same formatter.
run("npx", [
  "prettier",
  "--write",
  "--log-level",
  "warn",
  "packages/run-record/src/**/*.ts",
  "apps/docs/public/schema/**/*.json",
  "crates/backend/src/gg_reference.json",
]);

// 4. Compile the TypeScript that was just regenerated. Nothing in the browser reads
//    `packages/run-record/src/` — the package's `exports` map points at `dist/`, so
//    a Vite dev server serves whatever was last compiled. Emitting only the source
//    therefore leaves every console running against the *previous* contract until
//    someone happens to run a production build, and the failure is a module-level
//    `SyntaxError` naming an export that plainly exists in the source. Regenerating
//    and compiling are one act; do not split them.
run("npx", ["tsc", "-b", "packages/run-record"]);

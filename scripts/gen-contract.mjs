// Generate the Test Cabinet data contract — the TypeScript bindings and the JSON
// Schemas — from the Rust types that are its single source of truth.
//
// The work happens in three steps. The `contract-codegen` crate (see
// `crates/contract-codegen`) emits the TypeScript (`packages/run-record/src/`) and
// the JSON Schemas (`apps/docs/public/schema/`) from the Rust contract types, which
// derive `ts_rs::TS` + `schemars::JsonSchema` behind their `contract` feature. The
// Rust generator is correct but not pretty (ts_rs emits ragged whitespace), so the
// second step runs Prettier to make the committed output deterministic and
// conventional. CI regenerates and fails on any diff, so the committed artifacts
// always match the Rust source — hand-edits never survive. The last step compiles
// the regenerated TypeScript, because `dist/` — not `src/` — is what every consumer
// of the package actually imports.
//
// WHAT THIS NO LONGER DOES, AND WHY IT MATTERS TO WHOEVER RUNS IT. There used to be a
// step ahead of these that ran `gg reference` and wrote its output to
// `crates/backend/src/gg_reference.json`, because the backend served that projection
// and cannot depend on the crate that produces it. That was a second source of truth
// with a drift gate bolted on, and it is gone: gg writes the reference documents
// itself (`gg reference --out`, see `scripts/gg-reference.sh`), the backend image
// bakes them, and `tcab-backend` reads them at run time. Nothing here projects them,
// nothing commits them, and `scripts/ci/contract-drift.sh` has no gg half left.
//
// The practical consequence is that this script no longer BUILDS gg — so it no longer
// needs gg's eleven program-language toolchains, and neither does the CI job that runs
// it. What is left compiles `test-cabinet-core` and `test-cabinet-backend` only.
//
// Usage: `npm run gen:contract` (from the repository root).

import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

function run(cmd, args) {
  execFileSync(cmd, args, { stdio: "inherit" });
}

// 1. Emit raw TS + JSON from the Rust source of truth.
run("cargo", ["run", "--quiet", "-p", "contract-codegen"]);

// 1b. Mirror gg's built-in system-prompt templates into the TS contract, so the
//     console can seed its per-agent "System Prompt" editor with the exact default
//     an agent's `systemPromptTemplate` override starts from. There are two, chosen
//     by the agent's execution mode: the tool-calling arm names each capability's
//     free-standing tools, and the responses-as-code arm teaches the code protocol.
//     Both are language-agnostic — the code template names no function and is
//     rendered for every program language, with the little that is specific to one
//     gated inside it — so there is exactly one file to mirror per mode.
//     The `.hbs` files are the single source of truth (they are what the gg binary
//     renders); this keeps the TS copy from drifting, and CI's regenerate-and-diff
//     check enforces it.
{
  const tools = readFileSync("crates/gg/templates/system-tools.hbs", "utf8");
  const codePath = "crates/gg/templates/system-code.hbs";
  if (!existsSync(codePath)) {
    throw new Error(
      `no ${codePath} — gg's responses-as-code arm has no template`,
    );
  }
  const code = readFileSync(codePath, "utf8");
  writeFileSync(
    "packages/run-record/src/gg-system-prompt.ts",
    "// AUTO-GENERATED by scripts/gen-contract.mjs from crates/gg/templates/system-tools.hbs\n" +
      "// and crates/gg/templates/system-code.hbs.\n" +
      "// DO NOT EDIT BY HAND — edit the .hbs templates and run `npm run gen:contract`.\n\n" +
      "/**\n" +
      " * gg's built-in **tool-calling** system-prompt Handlebars template, verbatim — the\n" +
      " * default a tool-calling agent's `systemPromptTemplate` override starts from, and what\n" +
      " * the console seeds its per-agent System Prompt editor with for one. Partials are\n" +
      " * inlined, so it is self-contained; variables/branches are left intact.\n" +
      " */\n" +
      `export const DEFAULT_GG_SYSTEM_PROMPT_TEMPLATE = ${JSON.stringify(tools)};\n\n` +
      "/**\n" +
      " * gg's built-in **responses-as-code** system-prompt Handlebars template, verbatim — the\n" +
      " * default a code agent's `systemPromptTemplate` override starts from, whatever program\n" +
      " * language it writes.\n" +
      " *\n" +
      " * One template serves every language: it names no function, so what a call is spelled\n" +
      " * like is not in it, and the few things a model cannot discover about its own language\n" +
      " * are a segment gg gates while rendering. Self-contained, like its tool-calling sibling.\n" +
      " */\n" +
      `export const DEFAULT_GG_SYSTEM_PROMPT_TEMPLATE_CODE = ${JSON.stringify(code)};\n`,
  );
}

// 2. Normalize formatting so the committed artifacts are deterministic. Prettier
//    is pinned (see the root `package.json`) so the same input always formats the
//    same way, which is what makes the drift check trustworthy. Every file listed
//    here is one the drift check diffs, and that is the rule: an artifact it guards
//    has to come out of the same formatter, or a byte of whitespace turns CI red.
run("npx", [
  "prettier",
  "--write",
  "--log-level",
  "warn",
  "packages/run-record/src/**/*.ts",
  "apps/docs/public/schema/**/*.json",
]);

// 3. Compile the TypeScript that was just regenerated. Nothing in the browser reads
//    `packages/run-record/src/` — the package's `exports` map points at `dist/`, so
//    a Vite dev server serves whatever was last compiled. Emitting only the source
//    therefore leaves every console running against the *previous* contract until
//    someone happens to run a production build, and the failure is a module-level
//    `SyntaxError` naming an export that plainly exists in the source. Regenerating
//    and compiling are one act; do not split them.
run("npx", ["tsc", "-b", "packages/run-record"]);

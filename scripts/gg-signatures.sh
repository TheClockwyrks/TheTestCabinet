#!/usr/bin/env bash
#
# Regenerate every gg program language's signature catalogue into one directory.
#
#   scripts/gg-signatures.sh [OUT_DIR]        # default: target/gg-signatures
#
# THIS FILE IS THE ONLY LIST OF gg's PROGRAM-LANGUAGE ARMS IN THE REPOSITORY. Eleven arms, ten
# packages — `packages/gg-sandbox` reflects TypeScript and JavaScript from one set of declarations,
# because those two arms ARE one set of declarations and differ only in whether gg type-checks the
# program. A twelfth arm is one line below and nowhere else.
#
# WHAT A CATALOGUE IS. The whole of what a model is *told* about an arm's surface: every module,
# signature, argument, type and type member the responses-as-code system prompt renders and a
# documentation view answers with. Every word of it is reflected out of the SDK's own declarations by
# that language's own documentation tool — `tsc`, griffe, YARD, `purs`, javadoc, the Kotlin front
# end, rustdoc, `swiftc -emit-symbol-graph`, `clang++ -ast-dump=json`, Roslyn — so a description
# cannot drift from the declaration it describes.
#
# WHO RUNS IT, AND WHY THERE ARE EXACTLY TWO ANSWERS.
#
#   1. `crates/gg/build.rs`, with OUT_DIR set to its own `$OUT_DIR/signatures`. The catalogues are
#      generated by the build and `include_str!`d from there; not one of them is committed. That is
#      the point: a build of gg cannot embed a catalogue older than the SDK sources in the same
#      checkout, so the prompt a model is shown can never describe a surface the guest does not
#      export. There is no drift to gate, so there is no gate.
#
#   2. A PERSON, by hand, to READ one. This is not a fallback, it is a requirement: a reflector is a
#      program, reflectors have bugs, and the ones found here have been of the shape "the `@return`
#      prose was dropped", "a parameter description was truncated" and "only the first overload's
#      docs came through". Every one of those is invisible in the code and obvious in the emitted
#      JSON. So the catalogues are written somewhere a person can open them, and this script is how
#      you put them there:
#
#          scripts/gg-signatures.sh                 # -> target/gg-signatures/*.signatures.json
#          scripts/gg-signatures.sh /tmp/sigs       # -> anywhere else you like
#
# WHAT IT NEEDS. Every arm's documentation toolchain, which is every toolchain a devcontainer for
# this repository installs: Node and a repo-root `npm ci`, uv, Ruby, `purs`, a JDK, the Kotlin
# compiler, the `wasm32-unknown-unknown` standard library, the Swift toolchain, wasi-sdk and .NET.
# `scripts/ci/install-gg-toolchains.sh` installs the lot, idempotently, and every surface that builds
# gg runs it. Each arm below checks its own tool and names it if it is missing — the check lives
# there rather than here so there is one description of what an arm needs, in the script that needs
# it.
#
# THE NETWORK IT CAN WANT, which matters because `crates/gg/build.rs` runs this inside an ordinary
# `cargo build` and a build that reaches the internet halfway through is a build that fails on an
# aeroplane. There are exactly two reachable fetches, both cold-cache only and both pinned:
#
#   * the Rust, Swift and C++ arms generate WIT bindings first, and that fetches the pinned
#     `wit-bindgen` release from GitHub when the arm's `.build/` has none;
#   * the Ruby arm's reflector is YARD, and `packages/gg-sandbox-ruby/signatures.sh` installs the
#     pinned gem from rubygems.org when the interpreter cannot already resolve it.
#
# `scripts/ci/install-gg-toolchains.sh` installs the YARD one ahead of time precisely so that a
# build does not discover mid-compile that it wants to talk to a package registry, and it is run by
# every surface that builds gg. Nothing else here fetches anything: griffe comes out of uv's cache,
# and every compiler is already on the machine.
set -euo pipefail

# Repo root, independent of the caller's working directory: every arm below is named relative to it,
# and several of them change directory on the way to their own toolchain.
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

# The default lives under `target/`, which is already gitignored and already the directory this
# repository throws build output into — so a developer who runs this to read a catalogue does not
# have to think about cleaning up after it, and no arrangement of `git add` can commit one.
OUT_DIR="${1:-target/gg-signatures}"
mkdir -p "$OUT_DIR"
# Absolute from here on. Several reflectors run from a package directory, a `mktemp -d` or a
# `--codegen docs` scratch tree, and a relative destination would mean a different place in each —
# which is how a catalogue ends up written into a directory that is deleted on exit.
OUT_DIR="$(cd "$OUT_DIR" && pwd)"
export GG_SIGNATURES_OUT_DIR="$OUT_DIR"

# EMPTY THE DESTINATION FIRST, and note that this is not tidiness — it is the only thing that makes
# the completeness check at the foot of this file mean anything. The destination is not a scratch
# directory that starts empty: `crates/gg/build.rs` points it at `$OUT_DIR/signatures` under cargo's
# own `OUT_DIR`, which SURVIVES between builds, and a person reading catalogues re-runs this into the
# same `target/gg-signatures` every time. So on every machine that has built gg once, the previous
# run's eleven files are already sitting there. Without this, an arm that exited 0 having written
# nothing — or having written under a stem the host does not embed, which is what a reflector
# regression looks like — would leave last build's catalogue in place, non-empty, and the check below
# would pass on a file the current sources never produced. `include_str!` would then embed it, and a
# model would be told about a surface reflected from a checkout nobody remembers. Removing them makes
# absence real: what is here afterwards is what THIS run wrote.
#
# Only the catalogues are removed, never the directory: a caller is entitled to point this at a
# directory of their own that has other things in it, and `rm -rf "$OUT_DIR"` on a path taken from
# `$1` is a footgun with a very long barrel.
rm -f "$OUT_DIR"/*.signatures.json

# NO BYTECODE CACHES, for any of the four arms whose reflector is Python. Three of them import a
# sibling `tools/catalogue.py`, and the Python arm additionally loads `src/gg/catalogue.py` by path
# to read the operation table off the module itself — so by default each run drops a `__pycache__/`
# beside a file it read. Those directories are gitignored and harmless to a person, but
# `crates/gg/build.rs` names each package's `src` and `tools` subtrees as the inputs that should
# re-reflect a catalogue, and a step that writes into the tree it declared as its input is a build
# that invalidates the next one. The caches buy nothing here either: every reflector is run once, as
# a script, and never imported again.
export PYTHONDONTWRITEBYTECODE=1

# The one thing checked here rather than in an arm: the npm workspaces. Two arms come out of the
# pinned `typescript` that a repo-root `npm ci` installs, and "no such file or directory" from a
# package manager two directories away is a poor way to learn that a checkout was never installed.
if [ ! -x "$ROOT/node_modules/.bin/tsc" ]; then
	echo "error: the npm workspaces are not installed — no \`tsc\` at node_modules/.bin/tsc." >&2
	echo "       Run \`npm ci\` at the repository root." >&2
	exit 1
fi

# Run one arm, saying which one before it starts rather than after it finishes: the compiled arms
# take tens of seconds each and a silent minute reads as a hang.
#
# `$1` is what to print, `$2` is the script. A failure is reported with the arm named, because the
# tool that failed will have printed its own diagnostics several screens ago by then.
run_arm() {
	local label="$1" script="$2"
	echo "==> $label"
	if ! "$ROOT/$script"; then
		echo >&2
		echo "error: the $label arm's reflection failed ($script)." >&2
		echo "       If the message above names a missing toolchain, run" >&2
		echo "       scripts/ci/install-gg-toolchains.sh and try again." >&2
		exit 1
	fi
}

# The eleven arms. `packages/gg-sandbox` is first because it is the cheapest by an order of magnitude
# and because it is the one that fails on a checkout nobody installed — better to learn that in two
# seconds than after four minutes of javadoc, rustdoc and Roslyn. The rest are in the order the
# packages sit on disk, which is the order a reader of this list will look for them in.
run_arm "typescript + javascript" packages/gg-sandbox/signatures.sh
run_arm "python" packages/gg-sandbox-python/signatures.sh
run_arm "ruby" packages/gg-sandbox-ruby/signatures.sh
run_arm "purescript" packages/gg-sandbox-purescript/signatures.sh
run_arm "java" packages/gg-sandbox-java/signatures.sh
run_arm "kotlin" packages/gg-sandbox-kotlin/signatures.sh
run_arm "rust" packages/gg-sandbox-rust/signatures.sh
run_arm "swift" packages/gg-sandbox-swift/signatures.sh
run_arm "cpp" packages/gg-sandbox-cpp/signatures.sh
run_arm "csharp" packages/gg-sandbox-csharp/signatures.sh

# Every catalogue this script promises to have produced. Not a drift check — there is nothing to
# drift from — but a check that each arm did what it said it did. An arm that exits 0 having written
# nothing, or having written under a stem the host does not embed, would otherwise be discovered by
# `crates/gg/build.rs` as an `include_str!` of a file that is not there, several layers from the
# thing that went wrong. The worst outcome available here is a build that quietly hands a model an
# empty surface, so this is deliberately paranoid about emptiness as well as absence.
#
# It is a real check rather than a reassuring one only because the destination was emptied above: on
# a machine that has built gg before, every one of these files existed and was non-empty before the
# first arm ran.
CATALOGUES=(
	typescript javascript python ruby purescript java kotlin rust swift cpp csharp
)
for language in "${CATALOGUES[@]}"; do
	file="$OUT_DIR/$language.signatures.json"
	if [ ! -s "$file" ]; then
		echo "error: $language.signatures.json is missing or empty in $OUT_DIR." >&2
		echo "       Its arm above reported success, so this is a reflector writing the wrong" >&2
		echo "       file rather than a toolchain that is not installed." >&2
		exit 1
	fi
done

echo
echo "Wrote ${#CATALOGUES[@]} catalogues to $OUT_DIR:"
for language in "${CATALOGUES[@]}"; do
	printf '  %-12s %8s bytes\n' "$language" "$(wc -c <"$OUT_DIR/$language.signatures.json")"
done
